# Windows-консоль по умолчанию cp1252, и первая же кириллическая строка вывода
# роняет скрипт `UnicodeEncodeError`. Документированная команда обязана
# работать без внешнего `PYTHONIOENCODING`, поэтому поток настраивается здесь —
# тот же приём, что в `count_plan_edits.py` и `check_agents_index.py`.
#
# ОБА потока, не только `stdout`: отказы `assertions` (задача не найдена, нет
# раздела «Утверждения») печатаются в `stderr`, и без его настройки cp1252
# заменяет кириллицу на `backslashreplace`-escape'ы — падения нет, но
# сообщение нечитаемо, а «ёлочки» `«»` (cp1252 их кодирует байтом `0xab`)
# вперемешку с ASCII-escape'ами дают поток, который не декодируется как UTF-8
# вовсе (найдено ревью круга 2: `stderr` был настроен только наполовину —
# `count_plan_edits.py`/`check_agents_index.py` несут тот же изъян, но чинить
# их не в этой задаче).
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8")

# Заголовок задачи и граница блока: следующий заголовок ЛЮБОГО уровня `### ` —
# или разделитель `---` на отдельной строке. `\d+` в TASK_HEADER не совпадает
# по префиксу: группа сравнивается с номером задачи целиком, поэтому «Task 1»
# не путается с «Task 10».
TASK_HEADER = re.compile(r"^### Task (\d+):")
NEXT_HEADER = re.compile(r"^### ")
SEPARATOR = "---"

# Раздел «Утверждения»: список после этой строки и до следующего жирного
# заголовка раздела («Имена», «Проверка» и т.п. — форма `**Слово**` целиком на
# своей строке, БЕЗ отступа: строка-продолжение пункта, целиком состоящая из
# жирного текста (`  **термин**`), заголовком не считается — маркер сверяется
# с НЕотступленной строкой, `.strip()` перед сравнением не делается). Пункт
# верхнего уровня — строка `- …` БЕЗ отступа; вложенный — та же форма, но С
# отступом; продолжение — отступ без `- `.
ASSERTIONS_HEADER = "**Утверждения**"
BOLD_HEADER = re.compile(r"^\*\*[^*]+\*\*\s*$")
TOP_ITEM = re.compile(r"^- ")
NESTED_ITEM = re.compile(r"^\s+- ")

# Ограждённый блок кода (``` ... ```). Внутри него ни один структурный маркер
# не действует — это решение ревью round 1 (I5): маркер внутри ограждения не
# структурный маркер, а иллюстрация в тексте задачи, и разбор обязан её
# игнорировать целиком, включая сами строки-ограничители.
FENCE_MARKER = re.compile(r"^```")


@dataclass(frozen=True)
class Hunk:
    """Один git-hunk знаменателя `hunks`: путь, контекст `@@`, тело, счётчик.

    `raw_body` — ЕДИНСТВЕННАЯ нормализация тела, СЫРЫМИ БАЙТАМИ: только
    строки `+`/`-`, заголовок `@@` отброшен, хвостовые ASCII-пробельные байты
    сняты (`bytes.rstrip()` без аргумента — пробел, `\t`, `\n`, `\r`, `\x0b`,
    `\x0c`, и ничего юникодного: у `bytes` юникодного пробела не бывает вовсе,
    см. `_normalized_hunk_body`), склеены `\n` без хвостового переноса. Именно
    его, а не `body`, обязан хэшировать `hunk_id` (см. `_run_hunks`).

    `body` — ЭТО ЖЕ тело, но декодированное для показа человеку:
    `body = raw_body.decode("utf-8", errors="replace")`, ВСЕГДА, по
    построению, для каждого вида hunk'а без исключений. Из этого следует
    ОБРАТНОЕ: `raw_body == body.encode("utf-8")` держится ТОЧНО тогда, когда
    `raw_body` — валидный UTF-8 (декодирование и обратное кодирование тогда
    ничего не меняют), и расходится ровно там, где `raw_body` невалиден
    (невалидный байт → `U+FFFD` → другие байты при обратном кодировании) —
    это и есть внешнее ревью, BLOCKER 1: разные невалидные-UTF-8 правки одного
    файла раньше схлопывались в один и тот же `U+FFFD` ДО хэширования и
    получали один `H:` на двух разных правках.

    До круга 2 внешнего ревью `body` и `raw_body` строились ДВУМЯ РАЗНЫМИ
    нормализациями (текстовой, `str.rstrip()` — снимает ЛЮБОЙ юникодный
    пробел, и байтовой, `bytes.rstrip()` — только ASCII) вместо одной — и
    юникодный хвостовой пробел (например, NBSP `U+00A0`) снимался в `body`, но
    оставался в `raw_body`: показанное тело переставало соответствовать
    хэшируемому, а `git add` нетронутого файла с таким хвостовым пробелом
    менял `H:` (BLOCKER N2, тот же класс, что BLOCKER 3, только в общем виде).
    Единственная нормализация (`_normalized_hunk_body`, байтами) и `body` как
    её декодирование делают такое расхождение НЕВОЗМОЖНЫМ по построению, а не
    по внимательности при написании кода.

    `added`/`removed` — число строк `+`/`-` в теле; это независимое от
    `hunk_id` наблюдение, напечатанное как `+N/-M`, а не производная от
    строки `body`, которую вызывающему коду пришлось бы пересчитывать самому.
    """

    path: str
    context: str
    body: str
    raw_body: bytes
    added: int
    removed: int


# `diff --git a/<путь> b/<путь>` — заголовок секции файла. Начиная с круга 3
# внешнего ревью он БОЛЬШЕ НЕ РАЗБИРАЕТСЯ вовсе, ни для чего: заголовок
# принципиально неспособен нести путь однозначно — два РАЗНЫХ переименования
# (`a` → `"c b/d"` и `"a b/c"` → `d`) дают ПОБУКВЕННО ОДИНАКОВЫЙ заголовок
# `diff --git a/a b/c b/d`, и никакой разбор текста (ни жадный regex, ни
# перебор разрезов по множеству известных путей — обе техники стояли здесь в
# круге 1 и круге 2 и обе пали на этом входе) не восстановит потерянную
# информацию: её в заголовке физически нет. Путь этого модуля — ЦЕЛИКОМ из
# `git diff --raw -z HEAD` (`_raw_diff_records`), а строка `diff --git ` служит
# ТОЛЬКО маркером ГРАНИЦЫ секции (`_section_bounds`): обнаружением того, ГДЕ
# секция начинается, а не источником пути. Секции раздаются записям ПО ПОРЯДКУ
# (`_assign_sections`); см. докстринги `_raw_diff_records` и `diff_hunks`.

# `Binary files X and Y differ` — единственный маркер, который у git ЕСТЬ у
# двоичной секции ВМЕСТО `@@`-hunk'ов. Используется для ДВУХ вещей, и ОБЕ —
# без разбора пути: ОБНАРУЖЕНИЕ двоичной секции (`match(...) is not None`) и
# КЛАССИФИКАЦИЯ правки (добавлен/удалён/изменён, сравнением групп X/Y с
# КОНСТАНТНОЙ строкой `/dev/null`, см. `diff_hunks`) — путь (когда сторона не
# `/dev/null`) эти группы не дают вовсе и никогда не давали: он приходит
# вызывающему коду от `_raw_diff_records`, а не отсюда.
BINARY_DIFFER = re.compile(r"^Binary files (.+) and (.+) differ$")

# Заголовок текстового hunk'а: `@@ -l,s +l,s @@`, часто с хвостовым текстом
# контекста (`@@ ... @@ def foo():`). `.*@@` жадный — это не проблема: для
# `re.match` важно лишь НАЙТИ вторую пару `@@` где-то на строке, и жадность
# её не теряет.
HUNK_HEADER = re.compile(r"^@@ .*@@")

# `?? <путь>` — неотслеживаемый файл в `git status --porcelain`. Игнорируемые
# файлы под этот префикс не попадают вовсе (порцелан без `--ignored` их не
# показывает) — значит, «игнорируемый файл не даёт hunk'ов» выполняется самим
# выбором команды, без отдельной проверки `.gitignore` в коде.
UNTRACKED_STATUS = re.compile(r"^\?\? (.+)$")


def _fenced_mask(lines: Sequence[str]) -> list[bool]:
    """Для каждой строки — стоит ли она внутри ```-ограждения (сами границы — тоже внутри).

    Ограждение переключается по каждой встреченной строке-ограничителю; сама
    строка-ограничитель помечается «внутри» — она не структурный маркер, а
    часть иллюстрации, и не обязана участвовать в поиске границ блока,
    разделов или пунктов. Незакрытое до конца списка ограждение остаётся
    открытым — это осознанно: недописанный пример не должен «раскрыть»
    остаток документа обратно в структурный текст.
    """
    mask: list[bool] = []
    inside = False
    for line in lines:
        if FENCE_MARKER.match(line.strip()):
            inside = not inside
            mask.append(True)
        else:
            mask.append(inside)
    return mask


def _assertions_header_index(block: Sequence[str], mask: Sequence[bool]) -> int | None:
    """Индекс строки `**Утверждения**` в `block`, единственный источник правды.

    Единственное место, которое РЕШАЕТ, есть ли у задачи раздел «Утверждения»:
    и `assertion_items` (разбор пунктов), и `_run_assertions` (код возврата)
    обязаны спрашивать именно эту функцию, а не заводить свой поиск этой же
    строки. До круга 1 ревью оба места искали `**Утверждения**` одинаково
    наивно (без учёта ```-ограждений) и потому СОГЛАСОВАННО ошибались; когда
    круг 1 сделал `assertion_items` fence-aware, а `_run_assertions` — нет,
    признак раздвоился: маркер `**Утверждения**` ТОЛЬКО внутри примера кода
    заставлял наивную половину (`_run_assertions`) считать раздел существующим,
    а fence-aware половину (`assertion_items`) — честно возвращать `[]`, и
    задача без утверждений давала код 0 с пустым stdout (найдено ревью round
    2, Critical). Один источник правды делает такое расхождение невозможным
    структурно, а не только сегодня.

    `mask` — параметр, а не пересчёт внутри: единственный вызывающий, у
    которого уже есть маска для СВОИХ прочих нужд (`assertion_items`), не
    обязан считать ```-ограждения дважды; `_run_assertions`, которому маска
    больше ни для чего не нужна, считает её один раз специально для этого
    вызова.
    """
    for i, line in enumerate(block):
        if mask[i]:
            continue
        if line.strip() == ASSERTIONS_HEADER:
            return i
    return None


def repo_root() -> Path:
    """Корень репозитория — по ТЕКУЩЕМУ каталогу процесса, а не по `__file__`.

    `git rev-parse --show-toplevel` вызывается без `-C`: результат зависит от
    cwd, в котором запущен процесс. Так устроен `git()` в `count_plan_edits.py`,
    и от этого же зависит контракт задачи — путь `--plan` задаётся от корня
    репозитория, а запускать команду предполагается из `backend/`; прогон из
    корня обязан разрешать тот же путь.
    """
    completed = subprocess.run(
        ["git", "rev-parse", "--show-toplevel"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=True,
    )
    return Path(completed.stdout.strip())


def task_block(lines: list[str], task: int) -> list[str]:
    """Строки задачи `task` плана — от `### Task N:` до ближайшей границы.

    Границей блока служит ближайший следующий заголовок `### ` (заголовок
    ЛЮБОЙ задачи, а значит и её собственных подразделов не бывает — заголовки
    задач в плане плоские) либо строка-разделитель `---`. Если у последней
    задачи плана нет ни следующего заголовка, ни разделителя, блок идёт до
    конца списка строк.

    Задачи с таким номером нет в плане — возвращается пустой список. Это
    сигнал, отличный от «задача есть, а раздела „Утверждения“ в ней нет»:
    вызывающий код (`main`) обязан различать два отказа и печатать разные
    сообщения, поэтому здесь не бросается исключение и не возвращается
    какая-либо реплика текста — только пустота, которую вызывающий код
    проверяет сам.

    Строки внутри ```-ограждения (`_fenced_mask`) в поиске границы не
    участвуют: `### Task N:`, `### ` и голый `---`, встреченные там, — это
    иллюстрация в тексте задачи (например, пример markdown в разделе
    «Interfaces»), а не настоящая соседняя задача и не настоящий разделитель.
    Без этого пропуска пример кода мог бы оборвать блок раньше времени или
    заставить поиск заголовка найти чужой номер задачи внутри чужого примера.
    """
    mask = _fenced_mask(lines)

    start = None
    for i, line in enumerate(lines):
        if mask[i]:
            continue
        match = TASK_HEADER.match(line)
        if match and match.group(1) == str(task):
            start = i
            break
    if start is None:
        return []

    end = len(lines)
    for i in range(start + 1, len(lines)):
        if mask[i]:
            continue
        if NEXT_HEADER.match(lines[i]) or lines[i].strip() == SEPARATOR:
            end = i
            break
    return lines[start:end]


def assertion_items(block: list[str]) -> list[tuple[str, str]]:
    """Пары «идентификатор пункта, текст пункта» раздела «Утверждения» блока.

    Номер задачи читается из первой строки блока (`### Task N:` — так его и
    отдаёт `task_block`); если блок пуст или не начинается с такого заголовка,
    возвращается пустой список. Раздел ищется по строке `**Утверждения**` и
    обрезается по первому следующему жирному заголовку (`**Имена**»,
    «**Проверка**» и т.п.); если раздела нет вовсе, тоже возвращается пустой
    список — оба случая для вызывающего кода неотличимы ПО ЭТОЙ функции и
    должны проверяться им отдельно (см. `task_block` и `main`).

    Текст пункта передаётся как есть, включая хвостовую пунктуацию исходника
    (`;`, `.`) — функция перечисляет пункты, а не редактирует их прозу.
    Пункт из нескольких строк (продолжение — отступ без `- `) даёт ОДНУ пару:
    строки склеиваются пробелом.

    Чего функция НЕ делает: неотступленная непунктовая строка (прозаический
    абзац внутри раздела — например, врезка к задаче между двумя пунктами)
    молча ЗАВЕРШАЕТ текущий пункт и сама пунктом не становится — её текст не
    дописывается никуда и в вывод не попадает. Это осознанное решение, а не
    пропуск: план разрешает продолжением ТОЛЬКО ОТСТУПЛЕННУЮ строку (см.
    `docs/process/implementation.md`, «Схема идентификаторов»), а реализация
    раньше дописывала к последнему пункту ЛЮБУЮ непунктовую строку, отступ или
    нет, — врезка о задаче становилась частью текста последнего утверждения
    (найдено внешним ревью, замечание 5). Отказывать при такой строке тоже
    нельзя: замер по корпусу `docs/superpowers/plans/` показал живые планы с
    неотступленными непунктовыми строками внутри «Утверждения» (например,
    `2026-09-09-price-predicate.md`, задача 6) — отказ сломал бы разбор
    законного плана. Прозаический абзац — не элемент знаменателя (единица это
    пункт списка), поэтому его тихий пропуск не меняет счёт пунктов.

    Ограждённые ```-блоки (`_fenced_mask`) не участвуют ни в поиске самого
    раздела, ни в поиске его конца, ни в разборе пунктов: строка внутри
    ограждения никогда не заголовок, никогда не начало пункта — она
    дописывается к тексту ТЕКУЩЕГО пункта как есть (включая саму строку
    ограничителя), пока ограждение не закрылось. Так пример markdown внутри
    пункта («вот как выглядит ```» и т.п.) не обрывает раздел раньше времени
    и не превращает строку внутри примера в фантомный пункт.
    """
    if not block:
        return []
    header = TASK_HEADER.match(block[0])
    if header is None:
        return []
    task = header.group(1)

    mask = _fenced_mask(block)

    start = _assertions_header_index(block, mask)
    if start is None:
        return []

    body: list[str] = []
    body_fenced: list[bool] = []
    for i in range(start + 1, len(block)):
        # Заголовком-терминатором раздела считается только НЕотступленная
        # строка целиком из жирного (I4): `.strip()` перед сравнением не
        # делается, иначе строка-продолжение пункта вида `  **термин**`
        # молча обрывает раздел, а всё, что после неё, теряется.
        if not mask[i] and BOLD_HEADER.match(block[i]):
            break
        body.append(block[i])
        body_fenced.append(mask[i])

    items: list[tuple[str, str]] = []
    top_number = 0
    nested_count = 0
    current_id: str | None = None
    current_text: list[str] = []

    def flush() -> None:
        if current_id is not None:
            items.append((current_id, " ".join(current_text).strip()))

    for line, fenced in zip(body, body_fenced, strict=True):
        if not line.strip():
            continue
        if fenced:
            if current_id is not None:
                current_text.append(line.strip())
            continue
        top_match = TOP_ITEM.match(line)
        nested_match = None if top_match else NESTED_ITEM.match(line)
        if top_match:
            flush()
            top_number += 1
            nested_count = 0
            current_id = f"A{task}.{top_number}"
            current_text = [line[top_match.end() :].rstrip()]
        elif nested_match:
            flush()
            if top_number == 0:
                # Вложенный пункт без родителя (сирота) — буквы внутри
                # несуществующего верхнего пункта не бывает. Задача этого
                # инструмента — не терять единицу знаменателя, поэтому пункт
                # становится верхним, а не отбрасывается и не превращается в
                # мусорный `A<задача>.0a` (Minor F11 круга 1).
                top_number += 1
                nested_count = 0
                current_id = f"A{task}.{top_number}"
            else:
                nested_count += 1
                letter = chr(ord("a") + nested_count - 1)
                current_id = f"A{task}.{top_number}{letter}"
            current_text = [line[nested_match.end() :].rstrip()]
        elif line[:1] in (" ", "\t"):
            # Отступленное продолжение пункта — план разрешает только его
            # (замечание 5): дописывается к тексту ТЕКУЩЕГО пункта, если он
            # есть, иначе (отступ раньше первого пункта — не бывает валидно)
            # молча пропускается.
            if current_id is not None:
                current_text.append(line.strip())
        else:
            # Неотступленная непунктовая строка — прозаический абзац.
            # Заканчивает текущий пункт (что накоплено — записывается) и НЕ
            # становится новым пунктом: знаменатель не меняется, единица
            # знаменателя — пункт списка, а не прозаический абзац рядом с ним.
            flush()
            current_id = None
            current_text = []
    flush()
    return items


def emit(rows: Iterable[Sequence[str]]) -> None:
    """Печатает `rows`: поля строки через табуляцию, без шапки и без меток времени.

    Ширина строки — свойство вызывающей подкоманды, а не этой функции: у
    `assertions` строки из двух полей, у будущей `hunks` — из четырёх. `emit`
    их не считает и не проверяет, только соединяет табуляцией и печатает.
    """
    for row in rows:
        print("\t".join(row))


def _run_assertions(plan: str, task: int) -> int:
    """Реализация подкоманды `assertions`: два разных отказа, разные коды и сообщения.

    Отсутствующая задача N и отсутствующий в ней раздел «Утверждения» —
    РАЗНЫЕ отказы: первый значит «в плане нет такой задачи», второй — «задача
    есть, но выродилась и/или ещё не описана утверждениями». Оба должны
    завершаться ненулевым кодом с непустым сообщением в stderr и НЕ печатать
    пустой список в stdout с кодом 0 — тишина с нулевым кодом читалась бы как
    «у задачи нет утверждений», что для первого случая неверно, а для второго
    неотличимо от настоящей пустой задачи.

    Наличие раздела проверяется ЧЕРЕЗ `_assertions_header_index` — ТУ ЖЕ
    функцию, которой пользуется `assertion_items`, а не собственным поиском
    строки `**Утверждения**`. Так и был устроен этот отказ до круга 2: свой
    наивный (не знающий про ```-ограждения) поиск здесь СОГЛАСОВАННО, но
    неверно совпадал со старой наивной версией `assertion_items` — а когда
    круг 1 сделал `assertion_items` fence-aware, эта копия осталась наивной и
    стала давать код 0 с пустым stdout на разделе, целиком спрятанном внутри
    примера кода (найдено ревью round 2, Critical).
    """
    root = repo_root()
    plan_path = root / plan
    lines = plan_path.read_text(encoding="utf-8").replace("\r\n", "\n").split("\n")

    block = task_block(lines, task)
    if not block:
        print(f"задача {task} не найдена в плане {plan}", file=sys.stderr)
        return 2
    if _assertions_header_index(block, _fenced_mask(block)) is None:
        print(f"в задаче {task} плана {plan} нет раздела «Утверждения»", file=sys.stderr)
        return 3

    emit(assertion_items(block))
    return 0


def _git_text(args: list[str], *, check: bool = True) -> str:
    """Текстовый stdout `git <args>`, декодированный как UTF-8 с `errors="replace"`.

    `check=True` по умолчанию: для команд этого модуля (`diff HEAD`,
    `status --porcelain`) ненулевой код возврата — всегда настоящая ошибка
    git, а не штатный исход. Единственное исключение в этом файле не сюда:
    `git diff --no-index` не используется вовсе (см. `untracked_hunks`) —
    иначе пришлось бы отдельно допускать его код 1 («стороны различаются»,
    не ошибка).

    `errors="replace"`, а не строгий отказ по умолчанию: git считает файл
    ТЕКСТОМ, если в нём нет NUL-байта, даже если байты не образуют валидный
    UTF-8 (например, cp1251-содержимое), и печатает их в `git diff HEAD` как
    есть. Без `errors="replace"` поток чтения `subprocess` падал
    `AttributeError` на `None`-`stdout` (найдено ревью круга 1, K4) —
    прецедент решения уже в репозитории: `count_plan_edits.py` передаёт
    `errors="replace"` ровно по этой причине.
    """
    completed = subprocess.run(
        ["git", *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=check,
    )
    return completed.stdout


def _git_bytes(args: list[str]) -> bytes:
    """Сырые байты stdout `git <args>` — для блоба (`show HEAD:<путь>`).

    Байты, не текст: содержимое может быть двоичным, и `text=True` уронил бы
    вызов `UnicodeDecodeError`-ом на первом непечатном байте (та же причина,
    по которой assertions-тесты сравнивают CLI-вывод побайтно, а не текстом).
    """
    completed = subprocess.run(["git", *args], capture_output=True, check=True)
    return completed.stdout


def _section_bounds(lines: Sequence[str]) -> list[tuple[int, int]]:
    """Индексы `[start, end)` каждой секции `diff --git …` в списке строк.

    Границей секции служит строка `diff --git …`: она у git ЕСТЬ всегда,
    для любого изменённого файла, независимо от того, текстовый он или
    двоичный, добавлен, удалён или изменён. Пустой список строк (чистое
    дерево против `HEAD`) даёт пустой список границ — это законный вход, не
    отказ.

    Возвращает ГРАНИЦЫ, а не сами секции: `diff_hunks` строит из ОДНОГО
    прогона `git diff` и текстовое, и байтовое представление (`raw = _git_bytes(...)`,
    `text = raw.decode(..., errors="replace")`), и оба разбиты по `"\\n"` на
    одинаковое число строк с одинаковым порядком (перевод строки `\\n` —
    однобайтовый ASCII-символ, который никогда не участвует ни в какой
    многобайтовой UTF-8-последовательности и никогда не заменяется на
    `U+FFFD`, поэтому граница между строками у текста и у байтов совпадает
    ВСЕГДА, даже если содержимое строки — невалидный UTF-8). Одни и те же
    индексы, посчитанные один раз по текстовому списку (маркеры `diff --git
    `/`@@`/`Binary files … differ` — все ASCII, decode с `errors="replace"`
    их не искажает), нарезают ОБА списка синхронно — байтовый список нужен
    ровно там, где решается замечание 1 (RAW BODY текстового hunk'а).
    """
    bounds: list[tuple[int, int]] = []
    start: int | None = None
    for i, line in enumerate(lines):
        if line.startswith("diff --git "):
            if start is not None:
                bounds.append((start, i))
            start = i
    if start is not None:
        bounds.append((start, len(lines)))
    return bounds


def _normalized_hunk_body(lines: Iterable[bytes]) -> tuple[bytes, int, int]:
    """Тело hunk'а из строк `+`/`-` секции — БАЙТАМИ, ЕДИНСТВЕННАЯ нормализация.

    Единственное место, где решается, что считается ТЕЛОМ hunk'а: и хэш
    (`Hunk.raw_body`), и показанная человеку строка (`Hunk.body` —
    декодирование ЭТОГО ЖЕ результата, см. `_text_hunks_in_section`) идут
    отсюда. До круга 2 внешнего ревью существовали ДВЕ раздельные
    нормализации — эта, байтовая, и текстовая (`str.rstrip()` поверх уже
    декодированной строки) — и они расходились на хвостовом ЮНИКОДНОМ
    пробеле (например, NBSP `U+00A0`): `str.rstrip()` его снимает, а
    `bytes.rstrip()` — нет (это не ASCII-пробел). Расхождение снималось бы
    в `body`, но оставалось в `raw_body` — показанное тело переставало
    соответствовать хэшируемому, и `git add` НЕТРОНУТОГО файла с таким
    хвостовым пробелом менял `H:` (найдено внешним ревью, BLOCKER N2 — тот
    же класс, что BLOCKER 3, но в общем виде, не только для пустого файла).
    Одна нормализация здесь и декодирование её результата для показа (а не
    отдельный `str.rstrip()`) делают такое расхождение НЕВОЗМОЖНЫМ по
    построению.

    Строки контекста (пробел в начале) и `\\ No newline at end of file`
    (обратный слэш) сюда не попадают. `added`/`removed` — счёт строк `+` и
    `-` СРЕДИ ЭТИХ ЖЕ строк, до `rstrip`: хвостовый пробельный БАЙТ меняет
    тело (после нормализации — не меняет, снят), но не меняет то, `+` это
    строка или `-`.

    `rstrip()` без аргумента на `bytes` снимает ТОЛЬКО ASCII-пробельные
    байты (пробел, `\\t`, `\\n`, `\\r`, `\\x0b`, `\\x0c`) — это не выбор
    среди прочих, а свойство типа `bytes` (у него нет представления о
    «юникодном пробеле»), и именно оно и есть искомая гарантия: хвостовой
    юникодный пробел (закодированный, как правило, многобайтно — NBSP это
    `\\xc2\\xa0`) НЕ снимается и остаётся ЗНАЧАЩЕЙ частью тела (см.
    `docs/process/implementation.md`, где это теперь названо явно —
    «хвостовые ASCII-пробельные байты», не «хвостовые пробелы»).
    """
    body_lines: list[bytes] = []
    added = 0
    removed = 0
    for line in lines:
        if line.startswith(b"+"):
            added += 1
            body_lines.append(line.rstrip())
        elif line.startswith(b"-"):
            removed += 1
            body_lines.append(line.rstrip())
    return b"\n".join(body_lines), added, removed


def _text_hunks_in_section(path: str, section: Sequence[str], raw_section: Sequence[bytes]) -> list[Hunk]:
    """Текстовые hunk'и одной секции `diff --git` — по заголовкам `@@`.

    Секция без единого `@@` (например, чистая смена режима файла без правки
    содержимого) даёт пустой список — это не ошибка и не двоичный файл, а
    третий, вырожденный случай: у файла в этом прогоне попросту нет ни одного
    hunk'а знаменателя.

    `raw_section` — байтовый двойник `section` (та же секция, та же нарезка
    границ `@@`, см. `_section_bounds`): из него строится ЕДИНСТВЕННАЯ
    нормализация тела, `raw_body` (`_normalized_hunk_body`); `body` —
    декодирование ЭТОГО ЖЕ `raw_body`, а не отдельный расчёт по `section`
    (замечание 1 и BLOCKER N2 круга 2 — см. `Hunk`). `section` остаётся
    источником заголовка `@@` (`context`) для человека.
    """
    starts = [i for i, line in enumerate(section) if HUNK_HEADER.match(line)]
    hunks: list[Hunk] = []
    for position, start in enumerate(starts):
        end = starts[position + 1] if position + 1 < len(starts) else len(section)
        raw_body, added, removed = _normalized_hunk_body(raw_section[start + 1 : end])
        body = raw_body.decode("utf-8", errors="replace")
        hunks.append(
            Hunk(path=path, context=section[start], body=body, raw_body=raw_body, added=added, removed=removed)
        )
    return hunks


def _binary_hunk(root: Path, old_path: str, new_path: str, *, added: bool, deleted: bool) -> Hunk:
    """Синтетический hunk двоичной секции — по симметричной таблице задачи.

    `git diff` не умеет строить `+`/`-` строки по двоичному содержимому,
    поэтому тело здесь не от git, а от sha256 каждой стороны, которая
    РЕАЛЬНО существует: старая — из `git show HEAD:<путь>` (блоб коммита),
    новая — из рабочего дерева. Форма СИММЕТРИЧНА текстовому hunk'у: правка
    `A → B` и правка `C → B` дают РАЗНЫЕ тела (старый хэш входит в тело), а
    односторонняя форма `+binary <sha256 текущего>` их бы отождествила —
    и оставила удалённый файл вовсе без тела, потому что текущего содержимого
    у него нет. Контекст фиксирован — `@@ binary @@` — одинаков для всех трёх
    видов правки.

    `added`/`deleted` — флаги вызывающего кода (`diff_hunks`), посчитанные ИЗ
    САМОЙ секции (строка `Binary files X and Y differ`, сравнение X/Y с
    `/dev/null` — константной строкой, без разбора пути). `old_path`/
    `new_path` — переданы вызывающим кодом НАПРЯМУЮ из записи `git diff --raw
    -z HEAD` (`_raw_diff_records`), которой принадлежит эта секция: путь
    здесь вообще не читается из текста патча — ни из заголовка `diff --git`,
    ни из `Binary files … differ` (круг 3 внешнего ревью, M1/M2: заголовок
    `diff --git a/X b/Y` неизвлекаем однозначно в принципе — два РАЗНЫХ
    переименования на путях `a`→`"c b/d"` и `"a b/c"`→`d` дают ПОБУКВЕННО
    ОДИНАКОВЫЕ заголовки `diff --git a/a b/c b/d`, и никакой разбор текста не
    восстановит, какая сторона к какому пути относится — а `-z` НИКОГДА не
    экранирует путь, включая кавычку, обратный слэш и байты <0x20, тогда как
    обычный формат обязан их экранировать для однозначности синтаксиса).
    Переименованный ДВОИЧНЫЙ файл с изменённым содержимым — законный вход,
    где `old_path != new_path` даже для ОДНОЙ и той же секции (git печатает
    `rename from`/`rename to` И `Binary files … differ` в одной секции сразу,
    если сходство ниже 100%, но выше порога `--find-renames`), поэтому обе
    стороны читаются НЕЗАВИСИМО по СВОЕМУ пути, а не по одному общему.
    """
    context = "@@ binary @@"
    if added:
        new_bytes = (root / new_path).read_bytes()
        raw_body = f"+binary {hashlib.sha256(new_bytes).hexdigest()}".encode()
        return Hunk(
            path=new_path,
            context=context,
            body=raw_body.decode(),
            raw_body=raw_body,
            added=1,
            removed=0,
        )
    if deleted:
        old_bytes = _git_bytes(["show", f"HEAD:{old_path}"])
        raw_body = f"-binary {hashlib.sha256(old_bytes).hexdigest()}".encode()
        return Hunk(
            path=old_path,
            context=context,
            body=raw_body.decode(),
            raw_body=raw_body,
            added=0,
            removed=1,
        )
    old_bytes = _git_bytes(["show", f"HEAD:{old_path}"])
    new_bytes = (root / new_path).read_bytes()
    raw_body = (
        f"-binary {hashlib.sha256(old_bytes).hexdigest()}\n"
        f"+binary {hashlib.sha256(new_bytes).hexdigest()}"
    ).encode()
    return Hunk(path=new_path, context=context, body=raw_body.decode(), raw_body=raw_body, added=1, removed=1)


def _metadata_only_hunk(root: Path, path: str, raw_section: Sequence[bytes]) -> Hunk:
    """Синтетический hunk секции БЕЗ единого `@@` и без `Binary files … differ`.

    Три известных вида такой секции — чистое переименование (`similarity
    index`/`rename from`/`rename to`), смена режима файла (`old mode`/
    `new mode`) и добавление ПУСТОГО файла (`new file mode`/`index
    0000000..e69de29`, вечная константа git для пустого блоба). Раньше такая
    секция не давала ни одного hunk'а — она молча выпадала из знаменателя
    (найдено ревью круга 1, K5/K6/K7): утверждение A2.11 про двоичные файлы —
    «молчаливый пропуск запрещён» — это ПРИНЦИП, а не правило только для
    двоичных, и план уже показал технику: там, где `git diff` не выражает
    правку строками `+`/`-`, строится детерминированный синтетический hunk, а
    не пропуск.

    **Особый случай (замечание 3): добавление ПУСТОГО файла.** Один и тот же
    пустой файл, добавленный в рабочее дерево (untracked) и застейдженный тем
    же `git add`, — ОДНО и то же событие знаменателя, и обязан давать ОДИН и
    тот же `H:`. До правки они расходились: untracked-ветка (`untracked_hunks`)
    строит `@@ -0,0 +1,0 @@` с пустым телом (ей неоткуда взять `new file
    mode` — git ещё не видел файл), а эта функция строила `@@ metadata @@` с
    телом `"new file mode 100644"` — тот же файл получал два разных `H:` от
    ОДНОГО `git add`, ничего не поменявшего в содержимом (найдено внешним
    ревью, BLOCKER 3). Выбрана каноническая форма untracked-ветки: она ничего
    не ВЫДУМЫВАЕТ (staged-ветке пришлось бы напечатать `new file mode`,
    которого у untracked-файла нет и быть не может), а не наоборот.
    Обнаруживается по строке `new file mode` В САМОЙ СЕКЦИИ (файла не было в
    `HEAD`) И пустому содержимому по пути `path` в рабочем дереве — это
    СЕКЦИЯ-ЛОКАЛЬНЫЙ признак, не статус записи `git diff --raw`: `path`
    приходит от вызывающего кода (`diff_hunks`) как путь ЗАПИСИ, которой ПО
    ПОРЯДКУ досталась эта секция (`_assign_sections`; путь никогда не
    читается из текста патча, см. `diff_hunks`), а сам статус записи для
    классификации не используется вовсе.

    Тело ОСТАЛЬНЫХ (не этого особого) видов секции — сами описательные
    строки git ЭТОЙ секции (без первой, `diff --git …`: путь уже известен
    вызывающему коду), непустые, со снятым хвостовым ASCII-пробелом
    (`_normalized_hunk_body`-совместимая нормализация, БАЙТАМИ — та же
    гарантия «одна нормализация», что у текстового hunk'а, замечание N2
    круга 2), склеенные `\n` — не выдумка, а то, что git и так напечатал;
    разные виды правки различаются между собой этим же телом (у
    переименования — `rename from`/`rename to`, у смены режима — `old
    mode`/`new mode`).

    Строка `index <старый>..<новый> [режим]` ИСКЛЮЧЕНА из тела нарочно
    (найдено финальным сквозным ревью, S4): ширина хэшей в ней следует
    git-настройке `core.abbrev`, а не содержанию правки, и без исключения
    один и тот же сценарий на двух машинах с разным `core.abbrev` давал бы
    РАЗНЫЙ `hunk_id`. Переименование и смена режима строку `index ` не несут
    (проверено тестом на каждый вид отдельно). Контекст фиксирован — `@@
    metadata @@`; `added`/`removed` — оба 0.
    """
    is_new_file = any(line.startswith(b"new file mode") for line in raw_section)
    if is_new_file and (root / path).read_bytes() == b"":
        return Hunk(path=path, context="@@ -0,0 +1,0 @@", body="", raw_body=b"", added=0, removed=0)
    descriptive = [
        line.rstrip() for line in raw_section[1:] if line.strip() and not line.startswith(b"index ")
    ]
    raw_body = b"\n".join(descriptive)
    body = raw_body.decode("utf-8", errors="replace")
    return Hunk(path=path, context="@@ metadata @@", body=body, raw_body=raw_body, added=0, removed=0)


_RAW_STATUS_LINE = re.compile(r"^:\d+ \d+ [0-9a-f]+ [0-9a-f]+ (\S+)$")


def _raw_diff_records() -> list[tuple[str, str, str]]:
    """`(status, old_path, new_path)` на КАЖДУЮ запись `git diff --raw -z HEAD` — ЕДИНСТВЕННЫЙ источник путей.

    Источник — `git diff --raw -z HEAD --find-renames`: поля разделены NUL и
    НИКОГДА не экранируются (в отличие от обычного формата, где путь с
    кавычкой, обратным слэшем или байтом <0x20 заворачивается в кавычки с
    C-style escape-последовательностями). Каждая запись — `:<old-mode>
    <new-mode> <old-sha> <new-sha> <статус>`, затем один путь
    (добавление/удаление/правка/смена типа) или два (`R`/`C` — переименование
    или копия: старый путь, новый путь).

    `--find-renames` и `--no-relative` — ТЕ ЖЕ флаги, что несёт единственный
    вызов патча (`_whole_diff_args`), и несут они их НАРОЧНО одинаково: от
    `--find-renames` зависит, будет ли переименование ОДНОЙ записью и ОДНОЙ
    секцией или двумя и двумя (замечание 4 круга 1), а `--no-relative`
    отменяет пользовательскую настройку `diff.relative`, при которой git и в
    `--raw`, и в патче показывает ТОЛЬКО поддерево ТЕКУЩЕГО каталога
    (замерено: из подкаталога `sub/` дерева с девятью записями
    `diff.relative=true` оставляет ОДНУ — и в патче, и в `--raw`). Разойдись
    флаги — записи и секции перестали бы соответствовать по порядку, и
    `_assign_sections` отказала бы в лучшем случае, а в худшем привязала бы
    секцию не к тому файлу. `--ignore-submodules=none` — из того же ряда и по
    той же причине (круг 5): `diff.ignoreSubmodules=all` и
    `submodule.<имя>.ignore=all` выкидывают подмодуль из ОБОИХ выводов, и
    сдвиг его указателя молча исчезает из знаменателя.

    А вот `--submodule=short` здесь НЕ нужен, и это не забывчивость: он
    меняет РЕНДЕРИНГ секции патча (список коммитов вместо `diff --git `,
    либо развёрнутый внутренний diff), а формат `--raw` рисует подмодуль
    одной записью при любом значении `diff.submodule` — замерено на всех трёх
    значениях. Разница между наборами флагов двух команд намеренная и
    ровно такая: совпадают те флаги, что меняют СОСТАВ и ПОРЯДОК записей,
    различаются те, что меняют только вид текста патча.

    **Круг 3 внешнего ревью: путь БОЛЬШЕ НИГДЕ не извлекается из текста
    патча — эта функция единственный источник путей, и её результат
    полностью управляет перечислением.** До круга 3 путь для двоичных и
    metadata-секций разрешался разбором заголовка `diff --git a/X b/Y`
    (сперва наивно, потом через множество известных пар) — и это оказалось
    ПРИНЦИПИАЛЬНО неразрешимой задачей, а не недостаточно тщательным
    разбором: построено дерево, где `a` переименован в `"c b/d"`, а `"a
    b/c"` — в `d`; `git diff HEAD` печатает для ОБОИХ переименований
    ПОБУКВЕННО ОДИНАКОВЫЙ заголовок `diff --git a/a b/c b/d` — в самом
    заголовке физически нет информации, которая отличала бы одну правку от
    другой, и никакой перебор разрезов (ни «первый подошедший», ни
    «единственный подошедший») это не решает: подходят ОБА, и они разные
    (M2). Старый резолвер молча брал первый подходящий разрез — один путь
    исчезал из знаменателя, другой дублировался, `rc=0`, `stderr` пуст.
    Рядом — M1: путь с кавычкой (`a"b.txt`) ВСЕГДА экранируется в обычном
    формате (`"a\\"b.txt"`), независимо от `core.quotepath` (эта настройка
    гасит только octal-escape non-ASCII байт, а не необходимость
    экранировать сам символ кавычки), и наивная резка по фиксированному
    префиксу возвращала `/a\\"b.txt"` — путь, которого не существует.

    Решение — не чинить резку текста ещё раз, а исключить её как класс:
    `git diff --raw -z` даёт путь МАШИННО, без всякого текстового разбора, и
    `diff_hunks` берёт его отсюда ЦЕЛИКОМ, одной записью на изменённый файл,
    без какого-либо обращения к тексту патча за путём.

    **Круг 4: путь этой записи НЕ передаётся git'у ОБРАТНО как pathspec.**
    Круг 3 забирал патч каждого файла отдельным вызовом
    `git diff HEAD -- <путь>` — и это оказалось ТЕМ ЖЕ классом дефекта,
    переехавшим в новый механизм, потому что pathspec — это ШАБЛОН, а не имя
    файла. Он разрешается от ТЕКУЩЕГО каталога (а документированный вызов
    начинается с `cd backend`: три отслеживаемых файла из четырёх исчезали
    МОЛЧА, код 0); магические символы `[`, `*`, `?` и ведущее `:` в ОБЫЧНОМ
    имени (`a[bc]d.txt` рядом с `abd.txt` — ровно форма JS/TS-маршрута
    `[id].tsx`) подтягивают в секцию ЧУЖОЙ файл; а путь, совпавший с
    каталогом, забирает ВСЁ поддерево (каталог `pkg/`, заменённый файлом
    `pkg`: ЧЕТЫРЕ записи дали ШЕСТЬ элементов, тела `pkg/a.txt` и
    `pkg/b.txt` достались пути `pkg`). Флаг `--literal-pathspecs` этого НЕ
    чинит: рекурсия по каталогу — не магия шаблона, а сама семантика
    pathspec. Поэтому патч берётся ОДИН на всё дерево (`_whole_diff_args`),
    а записи и секции сопоставляет `_assign_sections` ПО ПОРЯДКУ.

    Заодно закрыт и N1 круга 2: у ОДНОЙ записи со статусом `T` (смена типа)
    ДВЕ смежные секции — это ИЗМЕРЕНО и записано правилом, а не позиционным
    `zip`, который на этом входе рвался.

    Побочная выгода: ДВА вызова git на весь прогон вместо N+1.
    """
    raw = _git_bytes(
        [
            "-c",
            "core.quotepath=false",
            "diff",
            "--raw",
            "-z",
            "HEAD",
            "--find-renames",
            "--no-relative",
            "--ignore-submodules=none",
        ]
    )
    fields = raw.decode("utf-8", errors="replace").split("\0")
    if fields and fields[-1] == "":
        fields.pop()
    records: list[tuple[str, str, str]] = []
    i = 0
    while i < len(fields):
        meta = fields[i]
        i += 1
        match = _RAW_STATUS_LINE.match(meta)
        status = match.group(1) if match else ""
        old_path = fields[i]
        i += 1
        if status[:1] in ("R", "C"):
            new_path = fields[i]
            i += 1
        else:
            new_path = old_path
        records.append((status, old_path, new_path))
    return records


def _whole_diff_args() -> list[str]:
    """Аргументы ЕДИНСТВЕННОГО `git diff HEAD` на ВСЁ дерево — БЕЗ pathspec вовсе.

    **Отсутствие `--` и путей здесь — не упрощение, а само содержание круга 4
    внешнего ревью.** Круг 3 передавал сюда путь записи как pathspec, и путь
    снова стал теряться и перепутываться — потому что pathspec это ШАБЛОН, а
    не имя файла (три воспроизведённых входа перечислены в докстринге
    `_raw_diff_records`: разрешение от ТЕКУЩЕГО каталога, магические `[`,
    `*`, `?`, ведущее `:`, и втягивание ВСЕГО поддерева при совпадении с
    каталогом). Команда БЕЗ pathspec ни одному из этих входов не подвержена:
    не с чем сопоставлять шаблон.

    `--no-relative` обязателен именно потому, что pathspec убран: без него
    пользовательская настройка `diff.relative=true` возвращает ту же потерю
    знаменателя другим путём — из подкаталога git показал бы ТОЛЬКО это
    поддерево. Замерено: пока `--no-relative` стоит, вывод этой команды (и
    `--raw -z` рядом) ПОБАЙТНО одинаков из корня репозитория и из любого
    подкаталога, с `diff.relative=true` в конфиге и без него.

    `--find-renames` — тот же флаг, что у `_raw_diff_records`, и по той же
    причине: записи и секции обязаны соответствовать ПО ПОРЯДКУ
    (`_assign_sections`), а от обнаружения переименований зависит, одна это
    запись с одной секцией или две с двумя.

    `--no-color`/`--no-ext-diff`/`--no-textconv` — защита от пользовательских
    настроек, которые подменили бы САМ ТЕКСТ патча (ANSI-раскраска, внешняя
    программа diff, textconv-фильтр): тело hunk'а хэшируется, и любой такой
    подмес сделал бы `H:` зависящим от чужого конфига.

    **`--submodule=short` — последняя настройка, менявшая ЧИСЛО секций на
    запись (круг 5).** `diff.submodule` рисует изменившийся подмодуль тремя
    разными способами, и два из них ломают соответствие записей и секций.
    Замерено на дереве с ДВУМЯ подмодулями, у первого из которых внутренний
    diff ПУСТ (указатель сдвинут пустым коммитом), а у второго меняются два
    файла:

    * `short` (умолчание git) — 2 записи, 2 секции, каждая своя;
    * `log` — 2 записи, 0 секций: секция подмодуля рендерится списком
      коммитов без единой строки `diff --git `. Суммы не сходятся, и
      `_assign_sections` отказывает ГРОМКО — исход плохой, но честный;
    * `diff` — 2 записи, 2 секции, но обе принадлежат ВТОРОМУ подмодулю
      (`s2/a.txt` и `s2/b.txt`): у первого внутренний diff пуст, и он не даёт
      НИ ОДНОЙ секции, а второй даёт ДВЕ. Суммы сходятся, отказ НЕ
      срабатывает, и под путём первого подмодуля печатается тело файла из
      второго — с кодом 0 и пустым `stderr`. Это ровно та молчаливая
      неверная привязка, которую круг 4 объявил структурно невозможной.

    С `--submodule=short` все три значения настройки дают 2 секции на 2
    записи. Флаг стоит ТОЛЬКО здесь: `--raw` рисует подмодуль одной записью
    при любом значении `diff.submodule` (замерено на тех же трёх), а флаг,
    который меняет только РЕНДЕРИНГ секции, на формат `--raw` и не влияет.

    **`--ignore-submodules=none` — здесь И в `_raw_diff_records`, потому что
    эта настройка меняет не рендеринг, а СОСТАВ записей.** `diff.ignoreSubmodules=all`
    и `submodule.<имя>.ignore=all` выкидывают подмодуль из ОБОИХ выводов
    сразу: суммы сходятся, отказа нет, но сдвиг указателя подмодуля молча
    исчезает из знаменателя ревью (замерено: 2 записи и 2 секции против 0 и
    0). Это вторая половина того же кардинального греха — не «правка не тому
    файлу», а «правки нет вовсе», — и лечится тем же форсированием. Флаг
    обязан стоять на ОБЕИХ командах: на одной он вернул бы расхождение сумм.
    """
    return [
        "-c",
        "core.quotepath=false",
        "diff",
        "HEAD",
        "--no-color",
        "--no-ext-diff",
        "--no-textconv",
        "--find-renames",
        "--no-relative",
        "--submodule=short",
        "--ignore-submodules=none",
    ]


def _sections_per_record(status: str) -> int:
    """Сколько секций патча принадлежит записи `--raw` с этим статусом: `T` — ДВЕ, всякой другой — ОДНА.

    Смена ТИПА файла (обычный файл ↔ симлинк) даёт ОДНУ запись `--raw` со
    статусом `T`, но ДВЕ смежные секции патча: unified-diff рендерит смену
    типа как удаление старого типа плюс добавление нового. Это ИЗМЕРЕНО на
    трёх формах смены типа — обычный → симлинк, симлинк → обычный, и смена
    типа при ПОБАЙТНО ОДИНАКОВОМ блобе (одна и та же sha по обе стороны):
    во всех трёх git печатает ровно две секции. Любой другой статус (`M`,
    `A`, `D`, `R…`, `C…`) даёт ровно одну — измерено на дереве, несущем
    восемь статусов разом.

    Статус сравнивается ПЕРВЫМ символом: `R`/`C` несут балл сходства
    (`R100`), `T` — нет, но единообразие важнее экономии.
    """
    return 2 if status[:1] == "T" else 1


def _assignment_breakpoint(records: Sequence[tuple[str, str, str]], available: int) -> str:
    """Локатор для сообщения об отказе: ГДЕ по порядку раздача перестала сходиться.

    Вынесено отдельной функцией, потому что это ДИАГНОСТИКА, а не часть
    раздачи: `_assign_sections` отказывает по СУММАМ (проверка дешёвая и не
    зависит от порядка), а вопрос «на какой записи» решается вторым, отдельным
    проходом и только когда отказ уже неизбежен.

    Три случая, и каждый называет что-то конкретное: записей нет вовсе, но
    секции есть; какой-то записи не хватило секций (её путь); секций больше,
    чем нужно (путь ПОСЛЕДНЕЙ записи, после которой остался хвост).
    """
    if not records:
        return f"записей нет вовсе, а секций патча {available}"
    cursor = 0
    for status, _old_path, new_path in records:
        count = _sections_per_record(status)
        if cursor + count > available:
            return f"секций не хватило записи `{new_path}` (статус {status or '?'})"
        cursor += count
    return f"лишние секции остались ПОСЛЕ последней записи `{records[-1][2]}`"


def _assign_sections(
    records: Sequence[tuple[str, str, str]], bounds: Sequence[tuple[int, int]]
) -> list[tuple[tuple[str, str, str], list[tuple[int, int]]]]:
    """Раздаёт секции патча записям `--raw` ПО ПОРЯДКУ — либо ОТКАЗЫВАЕТ ГРОМКО.

    Оба списка идут от git в ОДНОМ и том же порядке — это ИЗМЕРЕНО на дереве,
    где одновременно живут восемь статусов (`M`, `D`, `R100`, `T`, `A`,
    двоичный файл, имя с пробелом, имя со скобками): записи и секции
    соответствуют элемент в элемент, и единственное расхождение — статус `T`
    с его двумя секциями (`_sections_per_record`).

    **Расхождение сумм — отказ, а не догадка.** Молчаливое смещение привязки
    означало бы, что правка одного файла приписана ДРУГОМУ файлу (или
    исчезла), с кодом возврата 0 и пустым `stderr` — а именно это три круга
    подряд и происходило. Громкий отказ на невстречавшемся статусе — цена,
    которую этот инструмент платит осознанно: знаменатель ревью либо верен,
    либо его нет. Сообщение называет число записей, число секций и ВСЕ
    статусы, чтобы неизмеренный случай можно было воспроизвести и измерить,
    а не гадать по коду возврата.

    **И ПУТЬ — тоже (круг 5, I3).** Одних чисел и статусов мало: на дереве из
    ста записей сообщение печатало `M, M, M, …` и не давало ни одного
    локатора — воспроизводить было бы нечего. Локатор считается тем же
    проходом по порядку, что и раздача: называется путь ПЕРВОЙ записи,
    которой не хватило секций (`expected > len(bounds)`), либо — когда секций
    БОЛЬШЕ, чем нужно, и до последней записи всё сошлось — путь последней
    записи, ПОСЛЕ которой остались лишние секции.
    """
    expected = sum(_sections_per_record(status) for status, _old, _new in records)
    if expected != len(bounds):
        statuses = ", ".join(status or "?" for status, _old, _new in records) or "(нет записей)"
        raise RuntimeError(
            f"перечисление невозможно: {_assignment_breakpoint(records, len(bounds))}; "
            "записей `git diff --raw -z HEAD` — "
            f"{len(records)}, секций патча ожидалось {expected}, фактически {len(bounds)}; "
            f"статусы записей: {statuses}. Привязка секции к файлу была бы догадкой, "
            "а молчаливая догадка приписала бы правку не тому файлу."
        )
    assignments: list[tuple[tuple[str, str, str], list[tuple[int, int]]]] = []
    cursor = 0
    for record in records:
        count = _sections_per_record(record[0])
        assignments.append((record, list(bounds[cursor : cursor + count])))
        cursor += count
    return assignments


def diff_hunks() -> list[Hunk]:
    """Hunk'и рабочего дерева против `HEAD` — staged и unstaged вместе.

    `git diff HEAD` (без `--cached`, без голого `git diff`) — единственная
    команда, которая одновременно видит и то, что уже в индексе, и то, что
    ещё нет: файл, часть которого застейджена, а часть нет, даёт hunk'и обоих
    видов сам по себе, без отдельной ветки кода на этот случай. Индекс не
    трогается — читаются только `diff HEAD` (ОДИН вызов на весь прогон, см.
    ниже), `diff --raw -z HEAD` (`_raw_diff_records`) и, для двоичных файлов,
    блоб `HEAD` и рабочее дерево; `git add -N` нигде не вызывается.

    **Круг 4 внешнего ревью: ДВА вызова git на весь прогон — ОДИН патч на всё
    дерево (`_whole_diff_args`, БЕЗ pathspec) и ОДНА листовка
    `git diff --raw -z HEAD` (`_raw_diff_records`); секции раздаются записям
    ПО ПОРЯДКУ (`_assign_sections`).** Путь по-прежнему не читается из текста
    патча НИГДЕ и НИКОГДА — ни из заголовка `diff --git`, ни из строк
    `+++`/`---`, ни из `Binary files X and Y differ`: строка `diff --git `
    служит ТОЛЬКО маркером ГРАНИЦЫ секции (`_section_bounds`), а текст секции
    даёт только СОДЕРЖИМОЕ (тело, контекст, признак вида правки).

    Но путь и НЕ отдаётся git'у обратно: круг 3 забирал патч каждого файла
    отдельным вызовом `git diff HEAD -- <путь>`, и ТОТ ЖЕ класс дефекта
    переехал в новый механизм, потому что pathspec — ШАБЛОН, а не имя файла
    (`cd backend` терял почти весь знаменатель МОЛЧА; `a[bc]d.txt` рядом с
    `abd.txt` получал чужое тело; путь, совпавший с каталогом, втягивал всё
    поддерево). Перечень воспроизведённых входов и почему
    `--literal-pathspecs` их не чинит — в докстринге `_raw_diff_records`.

    Порядок записей и секций СОВПАДАЕТ элемент в элемент — это ИЗМЕРЕНО, а
    не предположено (дерево с восемью статусами разом), и единственное
    расхождение — статус `T`: смена ТИПА файла даёт ОДНУ запись и ДВЕ смежные
    секции (круг 2, BLOCKER N1). Это правило записано в `_sections_per_record`
    явно, а не спрятано в позиционный `zip`; не сойдись сумма с числом секций
    — `_assign_sections` ОТКАЗЫВАЕТ громко, вместо того чтобы сдвинуть
    привязку и приписать правку не тому файлу.

    Патч читается ОДИН раз байтами (`_git_bytes`, не `_git_text`): текстовое
    представление для поиска `@@`/`Binary files … differ`/описательных строк
    получается ЛОКАЛЬНЫМ `raw.decode("utf-8", errors="replace")`, а не вторым
    вызовом git — гарантировано (см. `_section_bounds`), что байтовые и
    текстовые строки нарезаны в ТОЧНОСТИ одинаково, а хэшируемое тело
    (`Hunk.raw_body`) идёт из СЫРЫХ байт, не из декодированной с
    `errors="replace"` строки (замечание 1 круга 1).
    """
    root = repo_root()
    records = _raw_diff_records()
    raw = _git_bytes(_whole_diff_args())
    text = raw.decode("utf-8", errors="replace")
    text_lines = text.split("\n")
    raw_lines = raw.split(b"\n")
    hunks: list[Hunk] = []
    for (_status, old_path, new_path), section_bounds in _assign_sections(records, _section_bounds(text_lines)):
        for start, end in section_bounds:
            section = text_lines[start:end]
            raw_section = raw_lines[start:end]
            text_hunks = _text_hunks_in_section(new_path, section, raw_section)
            if text_hunks:
                hunks.extend(text_hunks)
                continue
            binary_line = next((line for line in section if BINARY_DIFFER.match(line)), None)
            if binary_line is not None:
                old_side_text, new_side_text = BINARY_DIFFER.match(binary_line).groups()
                hunks.append(
                    _binary_hunk(
                        root,
                        old_path,
                        new_path,
                        added=old_side_text == "/dev/null",
                        deleted=new_side_text == "/dev/null",
                    )
                )
                continue
            # Ни одного `@@`, и не двоичная секция: переименование, смена
            # режима, добавление пустого файла и т.п. — знаменатель не
            # теряет элемент (K5/K6/K7 круга 1), а получает синтетический
            # hunk по той же технике, что и двоичные.
            hunks.append(_metadata_only_hunk(root, new_path, raw_section))
    return hunks


_SIMPLE_ESCAPES = {"\\\\": "\\", '\\"': '"', "\\t": "\t", "\\n": "\n", "\\r": "\r"}


def _unquote_git_status_path(token: str) -> str:
    """Снимает C-style кавычки `git status --porcelain` — сам путь ими не занят.

    git заворачивает путь в кавычки при пробеле и других «необычных» символах
    НЕЗАВИСИМО от `core.quotepath` — этот флаг влияет только на не-ASCII
    байты ВНУТРИ кавычек, не на само решение кавычить (найдено ревью круга 1,
    K2). Без снятия кавычек путь `read_bytes()` получал бы буквальные символы
    кавычки в имени и падал `OSError`.

    Внутри кавычек здесь встречаются только простые escape-последовательности
    (экранированная обратная косая черта, экранированная кавычка, управляющие
    символы) — октальных нет и не будет: этот модуль форсирует
    `-c core.quotepath=false` на КАЖДОМ вызове `git status`
    (`untracked_hunks`), и под этой настройкой git печатает не-ASCII байты
    сырыми, без кавычек и без октальных escape-последовательностей вовсе.
    Ветвь их разбора существовала здесь раньше и была мертва с рождения —
    сверщик показал её недостижимость (найдено финальным сквозным ревью, S7),
    и по правилу «мёртвое решение удаляется вместе с объяснявшим его
    комментарием» (`docs/process/implementation.md`, «Мёртвое либо
    эквивалентное решение») она снята, а не оставлена документацией
    несуществующего пути.
    """
    if len(token) < 2 or token[0] != '"' or token[-1] != '"':
        return token
    inner = token[1:-1]
    result: list[str] = []
    i = 0
    while i < len(inner):
        if inner[i] == "\\":
            two = inner[i : i + 2]
            if two in _SIMPLE_ESCAPES:
                result.append(_SIMPLE_ESCAPES[two])
                i += 2
                continue
        result.append(inner[i])
        i += 1
    return "".join(result)


def untracked_hunks() -> list[Hunk]:
    """По одному hunk'у «файл добавлен целиком» на неотслеживаемый неигнорируемый файл.

    Источник списка файлов — `git status --porcelain --untracked-files=all`,
    префикс `??`; игнорируемые файлы под него не попадают вовсе (без
    `--ignored` git их не показывает), поэтому отдельного обращения к
    `.gitignore` в этой функции нет и не нужно. `--untracked-files=all`
    обязателен: без него git сворачивает НОВЫЙ КАТАЛОГ в одну запись
    `?? newdir/`, и файлы внутри нигде не появляются в знаменателе — молчаливая
    потеря целой поддиректории (найдено ревью круга 1, K1). Путь из статус-строки
    снимается через `_unquote_git_status_path` (K2: git кавычит путь с
    пробелом независимо от `quotepath`).

    Двоичность определяется САМА, без обращения к git: наличие нулевого
    байта в первых 8000 байт файла — тот же эвристический признак, которым
    пользуется сам git при построении из `Binary files … differ`. Двоичный
    untracked-файл идёт по форме «добавление» таблицы двоичных hunk'ов
    (`+binary <sha256>`, `+1/-0`, `@@ binary @@`) — решение оркестратора:
    таблица разбита по ВИДУ правки, а untracked-файл — это всегда добавление;
    текстовое тело над двоичными байтами не определено.

    **Двоичность — ТОЛЬКО по нулевому байту, без второго, отдельного признака
    (Important I3, открыт с первой волны, закрыт в круге 3).** До этой правки
    файл БЕЗ NUL, но не декодируемый как UTF-8 (например, cp1251-текст без
    NUL, найдено ревью круга 1, K3), тоже уходил по форме «двоичный» —
    отдельным, СВОИМ признаком (`try: raw_bytes.decode("utf-8")`), которого у
    ЗАСТЕЙДЖЕННОЙ версии того же файла нет вовсе: git считает файл текстом
    везде, где нет NUL-байта, ДАЖЕ если он не образует валидный UTF-8, и
    `diff_hunks` (через `_text_hunks_in_section`) строит для него ОБЫЧНЫЙ
    текстовый hunk, а не двоичную форму. Тот же файл, untracked и staged,
    расходился по РАЗНЫМ ветвям построения тела — и получал РАЗНЫЙ `H:` от
    одного `git add`, не менявшего в файле ни байта (воспроизведено внешним
    ревью: `H:00e486cf` untracked против `H:86cec3f6` staged). Признак
    двоичности здесь СВЕДЁН к ЕДИНСТВЕННОМУ, тому же, что и у git самого —
    нулевому байту; файл без NUL идёт по текстовой форме ниже ВСЕГДА, что бы
    ни было в его байтах.

    Текстовый (по признаку «без NUL», НЕ «валидный UTF-8» — см. выше) файл
    даёт ОДИН hunk, где каждая строка файла становится строкой `+`
    (хвостовые ASCII-пробельные байты сняты той же нормализацией, БАЙТАМИ,
    что и у обычного hunk'а — `body` получается декодированием ЭТОГО ЖЕ
    `raw_body`, а не отдельным `str.rstrip()`: до круга 2 внешнего ревью эта
    ветка резала пробел на УЖЕ декодированной строке (`str.rstrip()`,
    снимающий любой юникодный пробел), и хвостовой NBSP/др. снимался здесь,
    но НЕ снимался у застейдженной версии того же файла
    (`_metadata_only_hunk`/`_text_hunks_in_section`, байтовый
    `bytes.rstrip()`) — BLOCKER N2, `git add` менял `H:` нетронутого файла),
    `removed` — всегда 0, а число `added` равно числу строк файла. Разбито по
    `b"\\n"`, не `.splitlines()` — та же причина, что и у `_section_bounds`
    (I1 круга 1): лишний юникодный разделитель внутри строки файла рвёт её и
    меняет тело/id непредсказуемо; сырые байты, не декодированная строка, —
    та же причина, что и у `_normalized_hunk_body`, и (теперь) единственный
    способ построить тело, не зависящий от того, валиден ли UTF-8: `body`
    для показа получается декодированием `raw_body` с `errors="replace"` —
    невалидный UTF-8-текст здесь не крашит и не переводит файл в двоичную
    форму, он просто показывается с `U+FFFD` вместо нечитаемых байт (см.
    `Hunk`).
    """
    root = repo_root()
    status = _git_text(["-c", "core.quotepath=false", "status", "--porcelain", "--untracked-files=all"])
    hunks: list[Hunk] = []
    for line in status.split("\n"):
        match = UNTRACKED_STATUS.match(line)
        if match is None:
            continue
        path = _unquote_git_status_path(match.group(1))
        raw_bytes = (root / path).read_bytes()
        if b"\x00" in raw_bytes[:8000]:
            raw_body = f"+binary {hashlib.sha256(raw_bytes).hexdigest()}".encode()
            hunks.append(Hunk(path=path, context="@@ binary @@", body=raw_body.decode(), raw_body=raw_body, added=1, removed=0))
            continue
        lines = raw_bytes.split(b"\n")
        if lines and lines[-1] == b"":
            lines.pop()
        raw_body = b"\n".join(b"+" + content.rstrip() for content in lines)
        body = raw_body.decode("utf-8", errors="replace")
        context = f"@@ -0,0 +1,{len(lines)} @@"
        hunks.append(Hunk(path=path, context=context, body=body, raw_body=raw_body, added=len(lines), removed=0))
    return hunks


def hunk_id(path: str, body: str | bytes) -> str:
    """`H:<8 hex>` — первые 8 hex от `sha256(path.encode("utf-8") + b"\\n" + body)`.

    `body` — СЫРЫЕ БАЙТЫ, если вызывающий код уже их построил (`_run_hunks`
    передаёт `hunk.raw_body`, см. замечание 1), либо строка — тогда она
    кодируется как UTF-8 здесь же. Обе ветки дают ОДИНАКОВЫЙ хэш для одного
    и того же ASCII/UTF-8-валидного содержимого — конкатенация байт двух
    закодированных кусков равна кодированию их конкатенации, так как UTF-8
    без состояния между символами, — поэтому существующий вызов с `str`
    (тесты, `Hunk.body` для двоичных/metadata-hunk'ов, где тело и так строится
    из ASCII: sha256-хэшей и описательных строк git) не меняет значение.
    Расходятся они только там, где `body`-строка несла бы `U+FFFD` вместо
    невалидного UTF-8-байта — а это ровно тот путь (`Hunk.raw_body`
    текстового hunk'а отслеживаемого файла), который замечание 1 и чинит.

    `body` приходит УЖЕ нормированным (см. `Hunk.raw_body`/`Hunk.body`): это
    значит, что сдвиг номеров строк в заголовке `@@` (в саму хэшируемую
    строку не входит) и хвостовой ASCII-пробельный байт на изменённой строке
    (снят до вызова этой функции, `_normalized_hunk_body`; юникодный
    пробельный символ — НЕ снят, он значащая часть тела) не меняют
    идентификатор — а тот же текст в другом
    файле меняет, потому что `path` — часть хэшируемой строки. Известный вход
    с известным ответом (оракул задачи, посчитан независимо от этого
    модуля): путь `backend/money/price.py` и тело из строк `+    if not
    value.is_finite():`, `+        return False`, `-    return value > 0`
    (склеены `\\n`) дают ровно `H:c81dd3dd`; тот же текст при пути
    `backend/money/other.py` — ровно `H:2292efa1`.
    """
    body_bytes = body.encode("utf-8") if isinstance(body, str) else body
    digest = hashlib.sha256(path.encode("utf-8") + b"\n" + body_bytes).hexdigest()
    return f"H:{digest[:8]}"


def _run_hunks() -> int:
    """Реализация подкоманды `hunks`: слияние, сортировка, позиционные суффиксы дублей.

    Порядок вывода — по пути файла, внутри файла по положению в `diff`:
    `diff_hunks()` и `untracked_hunks()` каждая уже возвращает hunk'и своего
    источника в порядке появления, но лишь явная сортировка ПО ПУТИ гарантирует
    порядок между двумя источниками — полагаться на то, что git и так обходит
    файлы отсортированно, было бы допущением, не проверенным этим кодом.
    Сортировка Python стабильна, поэтому порядок ВНУТРИ одного пути (а значит,
    и внутри одного файла — источник для данного пути всегда только один: файл
    не может быть одновременно отслеживаемым изменением и untracked) не
    нарушается.

    Суффиксы `.2`, `.3` у совпавших хэшей считаются заново на КАЖДОМ прогоне,
    по текущему порядку: раздельного состояния между прогонами нет и не
    нужно — это и есть то самое поведение, из-за которого более ранний по
    порядку дубликат сдвигает суффиксы соседей (спека §3.10): для этого не
    нужна отдельная ветка кода, только пересчёт "с нуля" при каждом вызове.

    Репозиторий без единого коммита — `git diff HEAD` отказывает кодом 128
    (`HEAD` не существует): падать здесь можно (молчаливая пустота была бы
    неотличима от честного «нет правок»), но ПОНЯТНЫМ сообщением, а не
    трассировкой `CalledProcessError` (найдено ревью круга 1, I2) — `git`
    уже написал причину в свой `stderr`, этот код только не даёт ей потеряться
    за трассировкой интерпретатора. `error.stderr` теперь БАЙТЫ (`diff_hunks`
    читает git через `_git_bytes`, не `_git_text`, см. замечание 1) —
    декодируется здесь тем же `errors="replace"`, что и раньше, это сообщение
    для человека, не хэшируемое значение.

    **Второй, более широкий `except` (замечание N1 круга 2 внешнего ревью).**
    Ошибки перечисления (например, `RuntimeError` громкого отказа
    `_assign_sections`, когда число секций патча не сошлось с числом записей
    `--raw`) не обязаны сигналиться ИМЕННО через `CalledProcessError` — до появления
    этого второго `except` (круг 2) любое ДРУГОЕ исключение выходило из
    функции трассировкой интерпретатора: смена ТИПА файла (обычный ↔
    симлинк) роняла ВЕСЬ перечислитель точно так же, как BLOCKER 2, который
    эта фаза уже чинила. Отказ инструмента ЛЮБОГО рода — это сообщение в
    `stderr` и код возврата, а не traceback; специфический `except` для git
    оставлен ПЕРВЫМ (он даёт более точное сообщение, «git отказал: …», для
    самого частого отказа), а общий — сетью безопасности для всего
    остального, что могло бы вылезти из `diff_hunks()`/`untracked_hunks()`.

    **Тип исключения — ЧАСТЬ сообщения (Important I2 круга 3).** Голый
    `str(error)` неотличим от законного отказа git: внедрённая программная
    ошибка (например, `AttributeError`/`TypeError` в самом перечислителе)
    печатала бы строку вроде `'str' object has no attribute 'decode'` без
    какого-либо намёка, что это НЕ git отказал, а сломался сам инструмент.
    `type(error).__name__` перед сообщением — минимальный, но необходимый
    контекст для того, кто читает `stderr` и решает, что делать дальше.
    """
    try:
        hunks = sorted(diff_hunks() + untracked_hunks(), key=lambda hunk: hunk.path)
    except subprocess.CalledProcessError as error:
        stderr = error.stderr
        if isinstance(stderr, bytes):
            stderr = stderr.decode("utf-8", errors="replace")
        message = (stderr or str(error)).strip()
        print(f"git отказал: {message}", file=sys.stderr)
        return 2
    except Exception as error:  # noqa: BLE001 — намеренно: см. докстринг выше.
        print(f"перечислитель отказал: {type(error).__name__}: {error}", file=sys.stderr)
        return 3
    seen: dict[str, int] = {}
    rows: list[tuple[str, str, str, str]] = []
    for hunk in hunks:
        raw_id = hunk_id(hunk.path, hunk.raw_body)
        count = seen.get(raw_id, 0) + 1
        seen[raw_id] = count
        display_id = raw_id if count == 1 else f"{raw_id}.{count}"
        rows.append((display_id, hunk.path, hunk.context, f"+{hunk.added}/-{hunk.removed}"))
    emit(rows)
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(prog="enumerate_review_units")
    # Подпарсеры заведены сразу, хотя подкоманда сегодня одна: следующая задача
    # добавляет `hunks` в этот же файл, и плоский парсер пришлось бы переписывать.
    subparsers = parser.add_subparsers(dest="command", required=True)

    assertions_parser = subparsers.add_parser("assertions", help="утверждения задачи плана")
    assertions_parser.add_argument("--plan", required=True, help="путь к плану от корня репозитория")
    assertions_parser.add_argument("--task", required=True, type=int, help="номер задачи в плане")

    subparsers.add_parser("hunks", help="git-hunk'и рабочего дерева против HEAD (staged и unstaged)")

    args = parser.parse_args()

    if args.command == "assertions":
        return _run_assertions(args.plan, args.task)
    if args.command == "hunks":
        return _run_hunks()
    return 1


if __name__ == "__main__":
    sys.exit(main())
