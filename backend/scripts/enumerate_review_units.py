"""Перечислитель единиц ревью плана: подкоманды `assertions` (задача 1) и `hunks` (задача 2).

Скрипт read-only: он только читает план/git и печатает строки, ничего не
пишет на диск и не трогает git — ни дерево, ни индекс (даже `git add -N`).
`assertions` превращает раздел «Утверждения» задачи плана в список пар
«идентификатор пункта, текст пункта»; `hunks` перечисляет git-hunk'и рабочего
дерева против `HEAD` (staged и unstaged вместе) плюс неотслеживаемые
неигнорируемые файлы — по одной строке на hunk. Обе печатают поля через
табуляцию и не несут отметок времени, чтобы два прогона сравнивались `diff`-ом.

Идентификатор пункта «Утверждения» — `A<задача>.<номер>` для пункта верхнего
уровня (нумерация с единицы) и `A<задача>.<номер><буква>` для вложенного
пункта (буква — `a`, `b`, … — считается заново внутри КАЖДОГО верхнего
пункта, а не сквозно по задаче). Пункт, продолженный на следующей строке БЕЗ
своего `- `, НО С ОТСТУПОМ, даёт ОДНУ строку вывода: текст продолжения
дописывается пробелом, а не заводит новый пункт. Неотступленная непунктовая
строка (прозаический абзац рядом со списком) продолжением НЕ считается — она
заканчивает текущий пункт и сама пунктом не становится (см. `assertion_items`).

Идентификатор hunk'а — `H:<8 hex>`, схема и нормализация тела описаны у
`hunk_id`; хэшируется ЕДИНСТВЕННАЯ нормализация тела, СЫРЫМИ БАЙТАМИ
(`Hunk.raw_body`, `_normalized_hunk_body`), с ASCII-only хвостовым пробелом
(`bytes.rstrip()` — юникодный пробел, например NBSP, значащий и не
снимается); показанная человеку строка (`Hunk.body`) — декодирование ЭТОГО
ЖЕ результата, а не отдельный расчёт. Путь БОЛЬШЕ НИКОГДА не читается из
текста патча (ни из заголовка `diff --git`, ни из `+++`/`---`) — он ЦЕЛИКОМ
из `git diff --raw -z HEAD` (`_raw_diff_records`). Патч берётся ОДИН на всё
дерево (`_whole_diff_args`) и БЕЗ pathspec вовсе — pathspec это ШАБЛОН, а не
имя файла (круг 4); он режется на секции по маркеру начала строки
`diff --git ` (обнаружение ГРАНИЦЫ, не разбор пути) и раздаётся записям ПО
ПОРЯДКУ: запись со статусом `T` владеет ДВУМЯ смежными секциями, всякая
другая — одной, а не сошлось — ГРОМКИЙ отказ, а не сдвиг привязки
(`_assign_sections`). Обнаружение переименований форсировано
(`--find-renames`), вывод отвязан от текущего каталога (`--no-relative`) —
оба флага на ОБЕИХ командах, независимо от пользовательских
`diff.renames`/`diff.relative`. Пустой файл, добавленный в рабочее дерево
и позже застейдженный тем же `git add`, даёт ОДИН и тот же `H:` — каноническая
форма `@@ -0,0 +1,0 @@` с пустым телом, общая для untracked- и staged-ветки.
Вложенный git-репозиторий, которого ещё нет в `HEAD`, даёт ОДИН и тот же `H:`
до и после того же `git add` — синтетическая форма `@@ nested-repo @@`
(`_nested_repo_hunk`) канонична для ОБЕИХ веток, путь БЕЗ хвостовой косой
черты (её печатает только `git status` для каталога, это не часть пути);
подмодуль, УЖЕ существующий в `HEAD`, у которого сдвинулся указатель, —
другой вид правки, с обеими сторонами, и синтетической формы не получает.
`argparse` заведён сразу с подпарсерами (задача 1 уже это учла), и `emit`
печатает строки ЛЮБОЙ ширины: два поля у `assertions`, четыре у `hunks`.

Запуск (путь `--plan` — от корня репозитория, независимо от того, откуда
запущена сама команда):

    cd backend && uv run python scripts/enumerate_review_units.py \
        assertions --plan docs/superpowers/plans/ДАТА-тема.md --task 4
    cd backend && uv run python scripts/enumerate_review_units.py hunks
"""

