"""Трансляция доменного отказа в HTTP — ЕДИНСТВЕННЫЙ экземпляр на все роутеры,
которые поднимают кодированные отказы (спека инфляции §2.12).

**Почему это отдельный модуль в `routers/`, а не функция в `crud/common.py`.**
Замером установлено, что FastAPI **не импортируется в `crud/` нигде** — это
свойство слоя целиком, а не одного файла, и функция, создающая `HTTPException`,
стала бы там первым нарушением. Расширение поля живёт в домене (`DomainError`
получил `code` и `context` и о форме HTTP-ответа не знает), трансляция — в
транспорте.

**Почему один экземпляр.** `_raise` жил в двух копиях (`analytics.py`,
`reports.py`), к ним добавился третий потребитель — роутер рядов, — и ветвление по
`code`, размноженное по трём файлам, дало бы три копии одного правила, то есть
запись 12 техдолга в утроенном виде. Экран, лист и редактор ряда обязаны получать
один контракт (DoD 23).

**Карты «код → статус» здесь НЕТ, и это решение.** Статус несёт сама ошибка.
Карта осмысленна там, откуда её взяли: у `category_overrides` есть код
`mapping_broken` — порча НАШИХ данных, — и он намеренно отсутствует в карте, чтобы
провалиться в `500`. Здесь все коды суть законные пользовательские состояния с
одним и тем же статусом, и карта не покупает ничего, кроме машинерии.

**ГРАНИЦА.** Свои `_raise` остаются у `contracts`, `rate_standards`, `references`,
`review` и `settings`: кодированных отказов они не поднимают, DoD 23 их не
касается, и переписывать их заодно — чужая поверхность.
"""
from __future__ import annotations

from typing import NoReturn

from fastapi import HTTPException

from crud.common import DomainError


def raise_domain_error(err: DomainError) -> NoReturn:
    """Поднять `HTTPException` по доменному отказу.

    `code is None` → `detail` строкой, как до фичи, ДО СИМВОЛА: все существующие
    отказы сравнения не меняются, и это условие DoD 1.

    `code` задан → `detail` объектом `{"code", "message", **context}`. Ключи
    контекста лежат РЯДОМ с `code`, а не вложенным узлом: клиенту так удобнее, а
    состав ключей у каждого кода фиксирован спекой.
    """
    if err.code is None:
        raise HTTPException(err.status_code, err.detail)

    detail: dict = {"code": err.code, "message": err.detail}
    for key, value in err.context.items():
        if key in detail:
            # Ключ контекста, накрывающий `code` или `message`, — ошибка НАША, а не
            # пользователя, и она обязана падать: перекрытие соврало бы читателю
            # тем самым полем, которое баннер печатает дословно, а отбрасывание
            # спрятало бы контекст, по которому клиент строит кнопку исправления.
            # `500` на своей ошибке — то же решение, каким `mapping_broken`
            # намеренно оставлен вне карты статусов у `category_overrides`.
            raise RuntimeError(
                f"Контекст отказа {err.code!r} содержит ключ {key!r}, который "
                "накрывает служебное поле ответа."
            )
        detail[key] = value
    raise HTTPException(err.status_code, detail)
