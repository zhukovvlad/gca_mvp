"""Приведение денежных величин к ценовому уровню выбранного месяца (спека
`2026-08-18-inflation-adjustment-design.md` §2.4, §2.5).

Ядро — чистые функции над `Decimal`. Ни базы, ни FastAPI, ни знания о том, что
приводится сравнение договоров: это общий денежный механизм рядом с `money/vat.py`,
и вторая фича (матрица, нормативы) подхватит его без переделки.

**Что здесь зафиксировано и почему это не оформление.**

`k(y)` — цепной коэффициент, декабрь года `y` к декабрю года `y−1`: стандартная
публикуемая форма, число сверяется с публикацией глазами (§2.3). Внутри года —
геометрически, показатель `m/12`, где январь = 1, декабрь = 12. При такой
конвенции декабрь-к-декабрю ложится точно, без аппроксимации, а `(m−1)/12`
означало бы «январь к январю» — показателя, которого не публикует никто (§2.4).
Любая дата внутри месяца есть уровень цен на конец месяца; день игнорируется
намеренно, поэтому дня нет и в `YearMonth`.

**Дата представляется отображением «год → показатель степени»**, а показатель
пары дат — разностью этих отображений. Из формы, а не из отдельного правила,
следует покрытие: строка ряда нужна ровно там, где разность ненулевая. Правило
«сплошной диапазон от минимального года до максимального» математически неверно —
оно потребовало бы 2024-й в переходе дек 2024 → дек 2025, где тот сокращается
тождественно, и запретило бы полностью вычислимое приведение (§2.5).

**Каноническая форма вычисления обязательна.** Тот же коэффициент, посчитанный
формой показателей и отношением уровней, расходится в последней цифре при
`prec=34`; без фиксации формы экран и лист разъехались бы, считая одно и то же
двумя путями. Канон: годы по ВОЗРАСТАНИЮ, на каждый год ОДНА операция возведения
в степень, затем последовательное умножение — всё внутри одного контекста.
Второй формулы в коде не заводится.

**Округления здесь нет.** Внутреннее приближение дробной степени при `prec=34`
бизнес-округлением не является; до копеек доводит `money.vat.quantize_money` на
слое показа, ровно как и у пересчёта по ставке НДС.

Экстраполяции нет: год, которого в ряду не оказалось, — отказ, а не подстановка
единицы. Число, выдуманное кодом, некому подписать (§2.9).
"""
from __future__ import annotations

import datetime as dt
import re
from collections.abc import Mapping
from dataclasses import dataclass
from decimal import (
    Context,
    Decimal,
    DivisionByZero,
    InvalidOperation,
    Overflow,
    localcontext,
)
from zoneinfo import ZoneInfo

#: Точность вычисления коэффициента. Замеры спеки (§2.5) и все ожидания тестов
#: сняты именно при 34 знаках; смена значения меняет последние цифры
#: коэффициентов, то есть это часть контракта, а не настройка.
INFLATION_PRECISION = 34

#: Бизнес-таймзона, в которой определяется «текущий» месяц (§2.7). Не часы ОС
#: сервера: если рабочий календарь компании ведётся в другой зоне, это правка
#: одной константы, а не поиск по коду.
BUSINESS_TIMEZONE = "Europe/Moscow"

_MONTHS_IN_YEAR = Decimal(12)

#: Контекст строится ЯВНО и не наследует глобальный: `localcontext()` без
#: аргумента копирует текущий контекст ВМЕСТЕ С ЕГО ТРАПАМИ (тот же довод и та же
#: форма, что у `_VAT_CONTEXT`). `InvalidOperation` в трапах здесь работает
#: защитой: неположительный коэффициент в дробной степени дал бы `NaN`, а `NaN`
#: доехал бы до ответа молча — схема держит `coefficient > 0`, и нарушение этого
#: инварианта обязано падать, а не размазываться по числам.
_INFLATION_CONTEXT = Context(
    prec=INFLATION_PRECISION,
    traps=[Overflow, DivisionByZero, InvalidOperation],
)

_TARGET_MONTH_RE = re.compile(r"^(\d{4})-(\d{2})$")


@dataclass(frozen=True, order=True)
class YearMonth:
    """Ценовой период: год и месяц. Дня нет намеренно — он игнорируется (§2.4).

    `order=True` нужен вызывающим: «цель раньше самой поздней сметы» — сравнение
    периодов, и второй способ их сравнивать заводить не надо.
    """

    year: int
    month: int


def parse_target_month(raw: str) -> YearMonth:
    """Разобрать `YYYY-MM`. Иначе `ValueError` — в HTTP-код его переводит роутер.

    День не принимается вовсе: он игнорируется по §2.4, и принять его значило бы
    обещать точность, которой нет.
    """
    match = _TARGET_MONTH_RE.match(raw or "")
    if match is None:
        raise ValueError(f"Целевой месяц ожидается в формате YYYY-MM, получено {raw!r}.")
    year, month = int(match.group(1)), int(match.group(2))
    if not 1 <= month <= 12:
        raise ValueError(f"Месяц вне диапазона 1…12: {raw!r}.")
    return YearMonth(year, month)


def _level_exponents(period: YearMonth, year: int) -> Decimal:
    """`E(y, m)[t]`: 1 при `t < y`, `m/12` при `t == y`, иначе 0 (§2.5)."""
    if year < period.year:
        return Decimal(1)
    if year == period.year:
        return Decimal(period.month) / _MONTHS_IN_YEAR
    return Decimal(0)


def year_exponents(source: YearMonth, target: YearMonth) -> dict[int, Decimal]:
    """Показатели степеней по годам: `E(target)[t] − E(source)[t]`, ненулевые.

    Годы, сокращающиеся тождественно, в результат НЕ попадают — из этого и
    состоит правило покрытия (§2.5). Диапазон перебора ограничен годами самих
    дат: ниже минимального оба отображения дают 1, выше максимального — оба 0,
    то есть разность там нулевая по построению.

    Разность считается внутри контекста точности наравне со степенью: `m/12` —
    периодическая дробь, и её округление входит в результат.
    """
    low = min(source.year, target.year)
    high = max(source.year, target.year)
    with localcontext(_INFLATION_CONTEXT):
        exponents = {}
        for year in range(low, high + 1):
            value = _level_exponents(target, year) - _level_exponents(source, year)
            if value != 0:
                exponents[year] = value
        return exponents


def required_years(source: YearMonth, target: YearMonth) -> list[int]:
    """Годы, чьи коэффициенты нужны этой паре дат, по возрастанию.

    Покрытие ВЫБОРКИ есть объединение таких списков по всем сметам (§2.9), а не
    диапазон: диапазон потребовал бы годы, которых формула не спрашивает.
    """
    return sorted(year_exponents(source, target))


def coefficient(exponents: Mapping[int, Decimal], values: Mapping[int, Decimal]) -> Decimal:
    """Коэффициент приведения по КАНОНИЧЕСКОЙ форме (§2.5).

    Годы по возрастанию, одна `**` на год, затем последовательное умножение.
    Порядок не косметика: при `prec=34` иной порядок оставил бы свободу в
    последнем знаке, и лист разошёлся бы с экраном.

    Пустые показатели дают ровно `1`, и ряд при этом не спрашивается ни разу —
    месяц в тот же месяц приводится без единой строки (DoD 5).

    Год, которого нет в `values`, поднимает `KeyError`: подстановка единицы была
    бы экстраполяцией, а покрытие проверяет вызывающий (`resolve_inflation`) до
    того, как хоть одна сумма умножена.
    """
    with localcontext(_INFLATION_CONTEXT):
        result = Decimal(1)
        for year in sorted(exponents):
            if year not in values:
                raise KeyError(
                    f"Коэффициент за {year} год не задан: приведение не вычислимо."
                )
            result *= values[year] ** exponents[year]
        return result


def adjust_amount(value: Decimal, factor: Decimal) -> Decimal:
    """Умножить сумму на коэффициент — ЕДИНСТВЕННОЕ место такого умножения.

    Тот же контекст, что у коэффициента: приведение и его вычисление обязаны
    жить в одной точности, иначе последний знак зависел бы от того, где
    умножили.
    """
    with localcontext(_INFLATION_CONTEXT):
        return value * factor


def _now_in(zone: ZoneInfo) -> dt.datetime:
    """Момент «сейчас» в названной зоне.

    Вынесено отдельной функцией ради проверяемости §2.7: зоны расходятся
    МЕСЯЦЕМ только у границы месяца, поэтому тест обязан фиксировать момент —
    иначе он был бы зелёным и при полностью игнорируемой зоне.
    """
    return dt.datetime.now(tz=zone)


def current_period(tz_name: str | None = None) -> YearMonth:
    """Текущий ценовой период в названной зоне (§2.7).

    Разрешается на СЕРВЕРЕ и возвращается клиенту: `Date.now()` в браузере — часы
    читателя, два человека получили бы два ответа, и ни один не воспроизводим.

    Зона читается ВНУТРИ вызова, а не связывается значением по умолчанию в
    сигнатуре. Разница не стилистическая: значение по умолчанию вычисляется один
    раз при определении функции, и подмена `BUSINESS_TIMEZONE` — та самая, которой
    DoD 18 проверяет, что зона вообще читается, — не действовала бы вовсе. Тест на
    зону тогда был бы зелёным при любой реализации.
    """
    moment = _now_in(ZoneInfo(tz_name or BUSINESS_TIMEZONE))
    return YearMonth(moment.year, moment.month)
