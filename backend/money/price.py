"""Предикат «это цена» и предикат «это пригодный вес» — правило заведено одно,
площадок применения несколько (спека правила цены,
docs/superpowers/specs/2026-09-09-price-predicate-design.md, §2.1-§2.2).

Модуль SQLAlchemy не импортирует: пакет `money/` держится чистым Python. SQL-
сторона того же правила — `_price_ok`/`_weight_ok` в `crud.analytics`, рядом с
`_NET_COST`, там, где уже читается VIEW отклонений. Обе площадки сверены тестом
(`tests/integration/test_price_predicate_sql.py`), а не переписаны одна из
другой вручную: расхождение обязано падать в CI, а не проявляться на стенде.
"""
from __future__ import annotations

from decimal import Decimal


def is_price(value: Decimal | None) -> bool:
    """Цена пригодна тогда и только тогда, когда она КОНЕЧНА и БОЛЬШЕ нуля.

    Пусто, ноль и отрицательное — не цена, но причину отсутствия предикат не
    называет: это её собственное дело выше по потребителям (решение пользователя
    09.09.2026, спека §2.1). `NaN`/`±Infinity` — тоже не цена, и это не
    надуманный вход: `_money` (`backend/services/estimate_import.py`)
    конвертирует ячейку через `Decimal(str(value))`, который эти три строки
    успешно проглатывает, а проверки конечности и ограничения на знак в схеме
    нет.

    Конечность проверяется ДО сравнения с нулём — тем же приёмом, что разбор
    ставки НДС в `estimate_import._vat_rate`: `Decimal("NaN") > 0` не возвращает
    `False`, а бросает `InvalidOperation`, и упавшее сравнение уронило бы
    вызывающего там, где ему нужен обычный отрицательный ответ, а не исключение.

    **Потребитель за пределами домена цены.**
    `crud.comparison._compute_median` зовёт эту функцию для отбора сравнимых
    ячеек медианы сравнения договоров — там величина не цена за единицу, а
    нетто корзины на квадратный метр (`BucketCell.net_per_sqm`), третий факт
    со своим носителем (задача 8 плана предиката цены). Формула переиспользована
    осознанно («конечно и больше нуля» подходит и здесь), а не по забывчивости
    — но следствие от этого не мягче: правка правила ЦЕНЫ отсюда молча меняет и
    правило СРАВНЕНИЯ договоров. Будущему правщику этой функции нужно видеть
    ЭТОГО потребителя явно, а не узнавать о нём постфактум из падений другого
    экрана.
    """
    if value is None:
        return False
    if not value.is_finite():
        return False
    return value > 0


def is_weight(value: Decimal | None) -> bool:
    """Вес пригоден тогда и только тогда, когда он КОНЕЧЕН и БОЛЬШЕ нуля.

    Формула совпадает с `is_price`, но факт — другой: у веса свой носитель
    (объём/количество позиции, а не цена за единицу) и своё место в матричном
    вкладе ячейки. Одно имя на два факта смешало бы их вопреки правилу «факт
    живёт в одном месте»; поэтому это отдельная функция, а не переиспользование
    `is_price` под другим названием — если правила когда-нибудь разойдутся
    (например, вес станет пригоден и на нуле), менять придётся только одно
    место, не разбирая, какой смысл где имелся в виду.
    """
    if value is None:
        return False
    if not value.is_finite():
        return False
    return value > 0
