"""Сверка чисел спеки с базой: две проверки на каждое утверждение.

1. **База по-прежнему даёт это значение.** Стенд живой и растёт: за одну сессию
   каталог вырос с 5 234 до 5 970 строк, и половина чисел первой редакции спеки
   протухла молча.
2. **Значение дословно стоит в тексте спеки.** Иначе опечатка в прозе живёт
   рядом с верным замером и выглядит как замер.

Процедурного правила «цитировать только из макета» недостаточно — именно так
спека попозиционного раскрытия разошлась со своим макетом.

Запуск:  python check_spec_numbers.py
Код возврата 1, если хоть одно утверждение не сошлось.
"""
from __future__ import annotations

import os
import sys

from evidence import MAIN, collect

sys.stdout.reconfigure(encoding="utf-8")

SPEC = os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir,
                    "2026-09-16-tender-changes-export-design.md")

#: Неразрывный пробел: разряды в спеке могут быть отбиты им, а сверять надо с
#: обычным. Записан ЭКРАНИРОВАННО — символом его не видно глазами в диффе.
NBSP = "\u00a0"


def spaced(value) -> str:
    """Число так, как оно набрано в спеке: разряды отбиты пробелом.

    ОКРУГЛЕНИЕ, а не усечение: `int()` на Decimal отбрасывает копейки и
    расходится со спекой на единицу — первая редакция этого сверщика так и
    «не нашла» четыре верных числа.
    """
    return f"{round(value):,}".replace(",", " ")


def claims(data: dict) -> list[tuple[str, str, str]]:
    """Тройки «о чём → как набрано в спеке → якорная фраза».

    Якорь обязателен: без него короткое значение вроде «12» подтверждается
    любым случайным вхождением, и страж выглядит строже, чем он есть.
    Проверяется АБЗАЦ, содержащий и значение, и якорь: строка для markdown
    слишком мелкая единица — текст переносится, и число с якорем оказываются
    на соседних строках одного утверждения.

    Соседства по абзацу мало, когда в абзаце несколько чисел: якорь «держится
    ТОЧНО» подтверждался абзацем, где рядом стоит другое число, и возврат
    построчного допуска в `MIX_SQL` не красил стража (предъявлено снятием).
    Поэтому у такого числа якорь — ФРАЗА с местом под значение (`{}`): она
    обязана совпасть целиком, и подстановка чужого числа её рвёт.
    """
    by_trace = {(t["tender"], t["participant"]): t for t in data["traces"]}
    main = by_trace[MAIN]
    second = by_trace[(2, 'ООО "АНТТЕК"')]
    third = by_trace[(3, 'ООО "ЕНИГЮН КОНСТРАКШН"')]
    catalog = dict(data["catalog"])
    edge = data["edge"]
    split = data["split"]
    rounding = data["rounding"]
    #: Сколько пар признак ПО АБСОЛЮТУ засчитал бы движением состава ОШИБОЧНО
    #: (§2.7) — считается ПОПАРНО в `evidence.py` (`mix_trigger_total`), а не
    #: арифметикой `mix_abs - mix_unit`: та разница честна как отдельное
    #: число, но занижает счёт на редкую границу (внешнее ревью, круг 2 —
    #: трасса «3 · АНТТЕК» даёт 95 арифметикой и 96 прямым счётом; в спеку
    #: идёт прямой счёт, потому что он и есть ответ на вопрос текста «сколько
    #: пар», а не побочный продукт вычитания). Якорь несёт МЕСТО ПОД ЗНАЧЕНИЕ.
    mix_trigger = [spaced(t["mix_trigger_total"]) for t in (second, main, third)]
    #: Внутри `mix_trigger` — подмножество, где сравнивать на единицу было
    #: МОЖНО, состав не изменился, а ИСПОЛЬЗУЕМЫЙ ОБЪЁМ изменился: доли те же,
    #: знаменатель другой. Отдельная величина, а не абзац-сосед: подмена одной
    #: тройки числами другой не красит стража, если у каждой свой якорь-фраза.
    mix_volume_move = [spaced(t["mix_volume_move"]) for t in (second, main, third)]
    #: Остаток того же подмножества: сравнить было можно, состав равен, объём
    #: НЕ менялся — значит расхождение абсолютов вызвала иная причина. Спека
    #: цитирует его нулями как доказательство «иных механизмов нет»; страж
    #: держит это утверждение под замером, а не под честным словом.
    mix_volume_other = [spaced(t["mix_volume_other"]) for t in (second, main, third)]
    #: Внутри `mix_volume_move` — пары, где абсолютная тройка И ЕСТЬ удельный
    #: числитель, то есть ИСПОЛЬЗУЕМЫЙ объём объясняет расхождение целиком.
    #: Отдельное число ровно потому, что оно меньше: «объём объясняет» было бы
    #: подразумеваемым, если бы его не считали. Слово «используемый» не
    #: украшение: `den` стоит под фильтром пригодности, а физический объём
    #: и число пригодных строк стоят соседними замерами ниже.
    mix_volume_exact = [spaced(t["mix_volume_exact"]) for t in (second, main, third)]
    #: Две НАБЛЮДАЕМЫЕ величины внутри `mix_volume_move`, каждая под своим
    #: именем и БЕЗ вывода о том, какая двинула `den`: число пригодных строк и
    #: вес всех строк клетки. Прежняя редакция называла первую «сменой
    #: расценённого МНОЖЕСТВА» (считая при этом ЧИСЛО) и приписывала ей причину
    #: «доступность цены, а не физический объём» — обе натяжки сняты в круге 4.
    mix_priced_rows = [spaced(t["mix_priced_rows_move"]) for t in (second, main, third)]
    mix_qty = [spaced(t["mix_qty_move"]) for t in (second, main, third)]
    #: Третья доля разбиения `mix_trigger_total`. Была единственной без своего
    #: числа — выводилась вычитанием, то есть не проверялась ничем.
    mix_not_cmp = [spaced(t["mix_not_comparable"]) for t in (second, main, third)]
    #: Направление объёма: спека утверждает, что оно НЕ ОДНО. Утверждение —
    #: значит замер. Без этих двух пунктов фраза «есть и рост, и убыль» стояла
    #: бы на честном слове, ровно как стояло до круга 3 слово «рост».
    mix_up = [spaced(t["mix_den_up"]) for t in (second, main, third)]
    mix_down = [spaced(t["mix_den_down"]) for t in (second, main, third)]
    #: Величина остатка у `exact`. Оговорку «причина, но не доказанно
    #: единственная» заменяет число: на стенде это копейки исходной сметы.
    exact_gap = max(t["mix_exact_gap"] for t in (second, main, third))
    #: «Состав цены как пятое основание отбора» держит в спеке отвергнутое
    #: решение (§2.7, §3) — якорь несёт МЕСТО ПОД ЗНАЧЕНИЕ (`{}`), а не только
    #: соседнюю фразу: якорь «работ» без места стоял рядом с числом и оставался
    #: зелёным, даже когда база разошлась с текстом («0, 1 и 0» вместо
    #: фактических «0, 0 и 0») — этот случай нашло только ручное чтение.
    mix_only = [spaced(t["mix_only_works"]) for t in (second, main, third)]

    out = [
        ("каталог стенда", spaced(catalog["TO_REVIEW"]), "TO_REVIEW"),
        ("строк обеих трасс", spaced(edge["строк"]), "0 из"),
        ("строк с нулевой ценой", spaced(edge["цена = 0"]), "unit_cost_total = 0"),
        ("строк базы", spaced(data["mix"]["строк базы"]), "из {} строк базы"),
        ("строк с тремя конечными составляющими",
         spaced(data["mix"]["с тремя конечными составляющими"]),
         "все {} несут три конечные составляющие"),
        ("состав сходится точно", spaced(data["mix"]["сходится точно"]),
         "держится ТОЧНО у {} из"),
        ("состав расходится в пределах копейки",
         spaced(data["mix"]["расходится в пределах копейки"]),
         "у оставшихся {} расхождение не больше копейки"),
        ("работ основной трассы", spaced(main["works"]), "из 877"),
        ("строк листа", spaced(main["rows"]), "из 1 365"),
        ("исчезновений со статьёй", spaced(main["gone_article"]), "исчезновений"),
        ("исчезновений по работе", spaced(main["gone_work"]), "вместо"),
        ("ложных исчезновений", spaced(main["gone_article"] - main["gone_work"]), "ложных"),
        ("пар соседних этапов", spaced(main["pairs"]), "пар"),
        ("строк с поздним началом", spaced(main["late"]), "позже первого"),
        ("строк с ранним концом", spaced(main["early"]), "раньше последнего"),
        ("ячеек с частичной ценой", spaced(main["partial_cells"]), "частичной"),
        ("номер устоял, основная", spaced(main["numbers_kept"]), "парах из"),
        ("работ двинулось", spaced(main["changed_works"]), "хотя бы раз"),
        ("ключей по lots.id", spaced(main["aw_by_lot_id"]), "ключей вместо"),
        ("ключей по lot_key", spaced(main["aw_by_lot_key"]), "ключей вместо"),
        ("самая тяжёлая группа", spaced(main["max_rows_in_group"]), "строк сметы"),
        ("различных переходов", spaced(main["transitions"]), "различных переходов"),
        ("доля пустых косвенных",
         f"{round(100 * main['indirect_zero_cells'] / main['cells_total'])} %",
         "косвенные расходы"),
        ("номер устоял, вторая трасса", spaced(second["numbers_kept"]), "из 2 369"),
        ("пар, вторая трасса", spaced(second["numbers_pairs"]), "907"),
        ("признак по абсолюту сработал бы ошибочно",
         ", ".join(mix_trigger[:2]) + " и " + mix_trigger[2],
         "{} пар на трёх трассах"),
        ("из них — изменение объёма при неизменном составе",
         ", ".join(mix_volume_move[:2]) + " и " + mix_volume_move[2],
         "при неизменном составе — {}"),
        ("из них — иная причина при сравнимых сторонах",
         ", ".join(mix_volume_other[:2]) + " и " + mix_volume_other[2],
         "иных причин расхождения — {}"),
        ("из них — используемый объём объясняет расхождение целиком",
         ", ".join(mix_volume_exact[:2]) + " и " + mix_volume_exact[2],
         "объёмом целиком объясняются {}"),
        ("из них — изменилось число пригодных строк",
         ", ".join(mix_priced_rows[:2]) + " и " + mix_priced_rows[2],
         "число пригодных строк изменилось в {}"),
        ("из них — двинулся физический объём",
         ", ".join(mix_qty[:2]) + " и " + mix_qty[2],
         "физический объём двинулся в {}"),
        ("пригодных строк базы", spaced(rounding["пригодных строк"]),
         "пригодных строк в базе {}"),
        ("из них равны round(unit × объём, 2)",
         spaced(rounding["из них равны round(unit × объём, 2)"]),
         "держится у {} строк"),
        ("худший остаток строки",
         f"{rounding['худший остаток строки']} ₽".replace(".", ","),
         "не больше {} на строку"),
        ("непригодных строк базы", spaced(rounding["непригодных строк"]),
         "непригодных строк {}"),
        ("непригодных строк с составляющими",
         spaced(rounding["из них несут составляющие"]),
         "составляющие несут {} из них"),
        ("сравнивать на единицу нечего",
         ", ".join(mix_not_cmp[:2]) + " и " + mix_not_cmp[2],
         "нечего — в {} парах"),
        ("объём вырос", ", ".join(mix_up[:2]) + " и " + mix_up[2],
         "вырос в {}"),
        ("объём убыл", ", ".join(mix_down[:2]) + " и " + mix_down[2],
         "убыл в {}"),
        ("худший остаток у exact",
         f"{exact_gap} ₽".replace(".", ","),
         "не больше {} на сторону"),
        ("состав как основание — работ добавляет",
         ", ".join(mix_only[:2]) + " и " + mix_only[2],
         "добавляет {} работ"),
        ("работ в нескольких статьях", spaced(split["split_works"]), "работ из 714"),
        ("работ на последнем этапе", spaced(split["works"]), "работ из 714"),
        ("денег в раздвоенных", spaced(split["money_split"]), "из"),
        ("денег всего", spaced(split["money_all"]), "приходится"),
    ]

    if main["worst_price"]:
        _gap, naive, correct = main["worst_price"]
        out.append(("худшая наивная цена", spaced(naive), "против верных"))
        out.append(("худшая верная цена", spaced(correct), "против верных"))

    for (a, b), count, _total in main["moves"]:
        out.append((f"переклассификация Э{a}→Э{b}", spaced(count), "статью сменили"))

    for stage, amount in main["aw_per_stage"].items():
        if amount:
            out.append((f"допработы, этап {stage}", spaced(amount), "этапе"))

    return out


def main() -> None:
    with open(SPEC, encoding="utf-8") as handle:
        text = handle.read().replace(NBSP, " ")
    # Абзац — блок между пустыми строками. Строка таблицы markdown тоже абзац
    # для этой цели: она целиком на одной строке. Пробельные последовательности
    # внутри абзаца схлопываются: фразовый якорь обязан совпадать через перенос
    # строки, иначе он держался бы за вёрстку, а не за текст.
    blocks = [" ".join(block.split()) for block in text.split(chr(10) * 2) if block.strip()]

    data = collect()
    checked = claims(data)
    failures = []
    for what, value, anchor in checked:
        if "{}" in anchor:
            phrase = anchor.replace("{}", value)
            hit = any(phrase in block for block in blocks)
        else:
            hit = any(value in block and anchor in block for block in blocks)
        if not hit:
            failures.append((what, value, anchor))
        print(f"  {'OK ' if hit else 'НЕТ'} {what}: {value}")

    print()
    if failures:
        print(f"НЕ СОШЛОСЬ: {len(failures)} из {len(checked)}")
        for what, value, anchor in failures:
            print(f"  {what}: ждал «{value}» в строке с «{anchor}»")
        sys.exit(1)
    print(f"Все {len(checked)} выбранных замеров стоят в спеке и сходятся с базой.")
    print("Это ВЫБОРКА, а не весь текст: страж проверяет перечисленные здесь")
    print("утверждения, и расширять список — часть правки спеки.")


if __name__ == "__main__":
    main()
