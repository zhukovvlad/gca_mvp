import { roundDecimalPercent } from "@/lib/format";

/**
 * Ступень подсветки отклонения от медианы (спека сравнения §2.5, правило 6).
 *
 * Отдельным модулем, а не внутри `ComparePage.tsx`: обе границы ниже — решение
 * реализации, а не значение спеки, поэтому их единственным носителем обязан быть
 * тест, а тест требует экспорта. Экспортировать функцию из файла с компонентами
 * запрещает `react-refresh/only-export-components` — и запрещает по делу: файл,
 * отдающий и компоненты, и утилиты, теряет горячую перезагрузку. Функция чистая,
 * ей своё место.
 *
 * **±10 % нейтральны — эта граница дана спекой дословно.** Вторая границей
 * ЧИСЛОМ спекой не задана: макет иллюстрирует две ступени статичной вёрсткой, а
 * не формулой (его `<script>` пересчитывает цифры, не CSS-классы), поэтому 30 %
 * — решение задачи 8. Появится число в спеке — заменить константу, а не
 * подгонять реализацию под неё задним числом.
 *
 * **Ступень выбирается по ПОКАЗАННОМУ числу, а не по сырому**, и это не
 * экономия: ячейка, на которой написано «+10 %», не окрашена никогда, а «+11 %»
 * окрашена всегда — цвет не расходится с цифрой, которую читает человек. Отсюда
 * и разбор величины из текста `roundDecimalPercent`: он строит его из `BigInt`
 * без разделителей разрядов, поэтому цифры вынимаются однозначно; появись там
 * группировка — связь придётся пересмотреть, а не латать регулярку. Несовпадение
 * с `DECIMAL_RE` даёт `sign === 0` и уходит в нейтральную ветку до разбора, так
 * что мусорная строка ячейку не окрасит.
 */
export const NEUTRAL_BAND_PCT = 10;
export const HIGH_BAND_PCT = 30;

export type DeviationTone = "flat" | "up-lo" | "up-hi" | "dn-lo" | "dn-hi";

export function deviationTone(
  value: string | null
): { text: string; tone: DeviationTone } | null {
  const rounded = roundDecimalPercent(value, 0);
  if (rounded === null) return null;
  const magnitude = Number.parseInt(rounded.text.replace(/[^0-9]/g, ""), 10);
  if (rounded.sign === 0 || magnitude <= NEUTRAL_BAND_PCT) {
    return { text: rounded.text, tone: "flat" };
  }
  const hi = magnitude > HIGH_BAND_PCT;
  return {
    text: rounded.text,
    tone: rounded.sign > 0 ? (hi ? "up-hi" : "up-lo") : hi ? "dn-hi" : "dn-lo",
  };
}
