/// <reference types="node" />
import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import chartSource from "./ContractCostChart.tsx?raw";
import dataSource from "./costChartData.ts?raw";

/**
 * Каждая CSS-переменная, на которую ссылается диаграмма, обязана существовать.
 *
 * **Чем выстрадано.** Компонент был написан с именами переменных ИЗ МАКЕТА
 * (`--accent`, `--accent-soft`, `--accent-text`, `--fg-tertiary`), а в
 * приложении токены зовутся иначе (`--accent-primary`, `--accent-primary-soft`,
 * …). Ни один из пяти не существовал. Последствия видно только глазами на живом
 * экране: неразрешимая `var()` делает объявление недействительным, и свойство
 * берёт начальное значение — у `fill` это ЧЁРНЫЙ, у `stroke` — `none`. То есть
 * столбцы стали чёрными, а штриховка промежутка, риска номинала и обе линии
 * медианы исчезли совсем. Геометрия при этом была верной, и все замеры стенда
 * — координаты, высоты, значения атрибутов — сошлись до пикселя.
 *
 * **Почему тест выглядит так.** Разрешённый цвет в прогоне не наблюдаем вовсе:
 * jsdom не считает каскад, а `getComputedStyle` вернёт саму строку `var(…)`.
 * Утверждать о цвете здесь нельзя в принципе
 * (`docs/insights/unobservable-in-the-runner.md`). Зато СУЩЕСТВОВАНИЕ токена —
 * обычный текст в двух файлах, и оно проверяется точно. Это правило 4 того же
 * инсайта: если свойство в прогоне ненаблюдаемо, проверку переносят туда, где
 * оно наблюдаемо, вместо того чтобы выражать её хитрым утверждением.
 *
 * Тест НЕ заменяет замер в браузере (цвет может существовать и быть
 * нечитаемым) — он ловит ровно опечатку и переименование токена, то есть тот
 * класс, который стоил всей палитры диаграммы.
 */

/*
  Исходники компонента читаются `?raw`-импортом Vite: неверный путь при таком
  импорте роняет СБОРКУ теста, а не даёт пустую строку. Палитру приходится
  читать с диска: `?raw` на CSS под vitest отдаёт ПУСТУЮ строку — он подменяет
  импорты стилей заглушкой, — и «все переменные объявлены» выполнялось бы тогда
  на любом входе. Поймала это предпосылка теста ниже, а не рассуждение;
  ссылка на node-типы нужна ровно поэтому.
*/
const css = readFileSync("src/index.css", "utf8");
const SOURCES: Record<string, string> = {
  "ContractCostChart.tsx": chartSource,
  "costChartData.ts": dataSource,
};

function cssVarsUsed(): string[] {
  const found = Object.values(SOURCES).flatMap(
    (source) => source.match(/var\(--[a-z0-9-]+\)/g) ?? []
  );
  return [...new Set(found)].map((v) => v.slice("var(".length, -1));
}

describe("диаграмма стоимости — токены оформления", () => {
  it("предпосылка: файлы прочитаны и ссылки на переменные в них есть, иначе тест пуст", () => {
    // Читается ИМЕННО палитра приложения: без этой проверки опечатка в пути дала
    // бы пустую строку и «всё объявлено» на любом входе.
    expect(css).toContain("--accent-primary:");
    const used = cssVarsUsed();
    expect(used.length).toBeGreaterThan(0);
    // И среди них есть акцентные — те самые, которыми красятся столбцы.
    expect(used.some((name) => name.includes("accent"))).toBe(true);
  });

  it("каждая переменная, на которую ссылается диаграмма, объявлена в index.css", () => {
    const missing = cssVarsUsed().filter((name) => !css.includes(`${name}:`));
    expect(missing).toEqual([]);
  });

  it("имена из МАКЕТА, которых в приложении нет, не должны появиться снова", () => {
    /*
      Перечислены те пять, что уже приезжали из макета. Список закрытый и
      короткий намеренно: он про конкретную ошибку, а не про запрет вообще —
      общий запрет уже даёт тест выше.
    */
    const fromMockup = ["--accent", "--accent-soft", "--accent-border", "--accent-text", "--fg-tertiary"];
    const used = new Set(cssVarsUsed());
    expect(fromMockup.filter((name) => used.has(name))).toEqual([]);
  });
});
