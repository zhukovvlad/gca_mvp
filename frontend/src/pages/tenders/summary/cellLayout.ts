import type { StageSummaryChange } from "@/types/domain";

/**
 * Раскладка ячейки свода — правила, общие для таблицы и её ячеек (спека
 * 2026-08-27-stage-summary-design.md §2.14).
 *
 * Модуль отдельный по той же причине, что и `cellCopy.ts`: файл, экспортирующий
 * React-компонент, не может экспортировать что-то ещё без потери fast refresh
 * (`react-refresh/only-export-components`). Правило поймал именно линт-гейт —
 * `tsc` и тесты на такое не смотрят.
 */

/**
 * Вертикальное выравнивание содержимого ячейки — ОДНО правило на всю строку
 * таблицы, а не на колонку.
 *
 * Найдено пользователем на стенде 28.08.2026: пилюли состояний прилипали к
 * ВЕРХУ ячейки этапа, тогда как такие же пилюли в «Торге» и «Вкладе в итог»
 * стояли по центру. Заметно это на строке, где хоть одна ячейка двухстрочная
 * (сумма и под ней изменение): строка выше, и односложные соседи повисают у
 * края.
 *
 * Правило: **число и любое многострочное содержимое — по верхней строке,
 * односложное НЕчисловое (пилюля, прочерк) — по центру высоты.** Обе половины
 * оплачены:
 *
 * - число сверху — потому что суммы этапов обязаны читаться СТРОКОЙ поперёк
 *   таблицы; у первой колонки изменения нет по построению, её ячейка на строку
 *   короче соседних в КАЖДОЙ строке, и центрирование увело бы её сумму на
 *   полстроки вниз всюду (решение пользователя 28.08.2026);
 * - односложная пилюля по центру — потому что выравниваться ей не с кем, и
 *   центр читается как «ячейка целиком про это».
 *
 * Макет гейта 1 объявляет `vertical-align: baseline` ВСЕМ ячейкам `table.pass`,
 * то есть держит на верхней линии и пилюли тоже. Первая половина правила с ним
 * СОВПАДАЕТ; отклонение — только вторая, и оно по прямой просьбе пользователя
 * (спека §2.14).
 *
 * Условие, без которого правило не сходится ни при каком выравнивании: у всех
 * ячеек строки должна быть ОДИНАКОВАЯ коробка. Ячейки этапов были сырыми `<td>`
 * без отступов против `p-2` у соседей — замер показал 8 px расхождения первых
 * строк, ровно чужой `padding-top`.
 */
export function cellAlignClass(showsNumber: boolean, hasSecondLine: boolean): string {
  return showsNumber || hasSecondLine ? "align-top" : "align-middle";
}

/**
 * Показывает ли значок изменения ЧИСЛО (процент либо абсолютную дельту) — в
 * отличие от пилюли и прочерка. Нужен колонке «Торг»: там `ChangeBadge` стоит
 * без состояния рядом, и выравнивание выбирается по виду изменения.
 */
export function isNumericChange(change: StageSummaryChange): boolean {
  return change.kind === "percent" || change.kind === "abs_only";
}

/**
 * Колонка классификатора зажата по ширине — `min-width: 250px`,
 * `max-width: 420px`, ровно как на макете гейта 1 (`table.pass`,
 * `th.art, td.t`). Реализация это ограничение ПОТЕРЯЛА, и таблица с авторазметкой
 * отдавала колонке столько, сколько просило самое длинное наименование: замер на
 * стенде 28.08.2026 — при свёрнутых статьях 459,8 px (34 % контейнера) и всё
 * помещалось, при раскрытых 752,81 px (55,8 %), таблица становилась шире
 * контейнера на 253 px, и «Торг» с «Вкладом в итог» уезжали за правый край.
 *
 * Зажим ставится на ВСЕ ячейки первой колонки — шапку, строки статей и обе
 * строки подвала: ширину колонки в авторазметке диктует самая широкая ячейка, и
 * пропущенная строка вернула бы прежнее поведение целиком.
 *
 * `whitespace-normal` здесь — не украшение, а условие работы зажима: примитив
 * `TableCell`/`TableHead` из shadcn несёт `whitespace-nowrap`, и с ним
 * наименование не переносится вовсе. Он ломает строку ПО ПРОБЕЛАМ; за
 * одиночный длинный токен (слипшееся слово, код без пробелов) отвечают
 * `break-words` и `min-w-0` на самом наименовании ниже — первый разрешает
 * разрыв внутри слова, второй снимает `min-width: auto` у флекс-элемента, без
 * которого он не сузится. Три класса — три разные половины одной работы, и
 * снятие любого возвращает часть дефекта. Замер на стенде показал, чем это кончается:
 * колонка честно вставала в 446 px, а текст на 100 символов вылезал из своей
 * ячейки на 130 px и ЛОЖИЛСЯ ПОВЕРХ первой денежной колонки — 25 таких ячеек при
 * раскрытых статьях. То есть зажим без переноса делает хуже, чем его отсутствие.
 *
 * Вместе с зажимом строка содержимого ячейки выравнивается ПО ВЕРХУ
 * (`items-start` вместо `items-center`): наименование теперь бывает в две-три
 * строки, и при выравнивании по центру треугольник раскрытия и код статьи
 * уезжали бы к середине абзаца вместо его первой строки. То же у
 * «Нераспределённого» — наименование там короткое, но правило одно на колонку,
 * а не на строку.
 *
 * Про число 420: это ПОТОЛОК ПРЕДПОЧТИТЕЛЬНОЙ ширины, а не итоговой. При
 * `table-layout: auto` и `w-full` браузер сперва считает предпочтительные
 * ширины (тут `max-width` и связывает), а СВОБОДНОЕ место потом раздаёт поверх
 * — поэтому на широком окне замер показывает 446 px, и это не полработы.
 * Заработанный инвариант формулируется не «≤ 420 px», а «колонка не растёт от
 * содержимого»: замеры со свёрнутыми и раскрытыми статьями совпадают до сотых.
 */
/*
  `border-r` — разделитель закреплённой колонки. Макет рисует его тенью
  (`box-shadow: 1px 0 0 0`), в реализации его не было вовсе (замер: `box-shadow:
  none`), и колонка при прокрутке не отличалась от просто первой — а линия и есть
  единственный признак того, что содержимое уезжает ПОД неё. Тенью не делаем:
  граница живёт в той же системе, что остальные линии таблицы.
*/
/*
  Модуль-хозяин — намеренно `cellLayout.ts`, а не `StageSummaryTable.tsx`: и
  таблица свода (`CategoryRowGroup`, строки подвала), и `PositionDrilldown.tsx`
  рисуют строки ОДНОЙ И ТОЙ ЖЕ колонки одной и той же таблицы (задача 12,
  приёмка на стенде нашла разъезд) и обязаны делить РОВНО ЭТУ строку классов, а
  не повторять её текстом — иначе повторится сам дефект, который здесь
  чинится: без нужного набора классов `TableCell` наследует базовый
  `whitespace-nowrap` (`components/ui/table.tsx`), и одна строка со сплошным
  нередактированным текстом (спека §1.6/§2.10 — до 5077 знаков без переносов,
  схлопнутых `whitespace-normal`) раздувает КОЛОНКУ ВСЕЙ ТАБЛИЦЫ (`table-layout:
  auto` разделяет ширину столбца между всеми ячейками одного индекса) —
  замерено на стенде: 5738 px вместо ожидаемых ~250–446 (см. коммент выше про
  420). Константа изначально жила в `StageSummaryTable.tsx` и экспортировалась
  оттуда; `PositionDrilldown.tsx` уже импортирует компонент таблицы для
  собственной рекурсии (`import { PositionDrilldown } from "./PositionDrilldown"`
  идёт из `StageSummaryTable.tsx`), так что обратный импорт константы из
  таблицы замкнул бы модульный цикл — рабочий лишь потому, что константа
  читается во время рендера, а не при инициализации модуля. `cellLayout.ts`
  уже существует ровно для такого разделения (см. докстрок файла) — нейтральный
  модуль, оба потребителя импортируют константу оттуда, и цикла не возникает.
*/
export const FIRST_COL_CLASS =
  "sticky left-0 min-w-[250px] max-w-[420px] whitespace-normal border-r border-border-subtle align-top";
