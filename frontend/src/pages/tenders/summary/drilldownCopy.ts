/**
 * Пилюля допработы. Лот называется ТОЛЬКО когда в ответе он не один: у двух
 * лотов ссылка совпадает, и без лота две разные работы выглядели бы
 * одинаково подписанными (§2.7); на одном лоте лишнего слова нет.
 */
export const extraPill = (ref: string, lot?: string | null) =>
  lot ? `допработы · ${lot} · ${ref}` : `допработы · ${ref}`;

/**
 * Пилюля диагностической строки без каталожной привязки (§2.7) — КОРОТКАЯ,
 * не повтор наименования: строка уже несёт свой полный серверный `title`
 * («Строки без каталожной привязки (N)») в самой строке (§2.10), и печатать
 * тот же текст ещё раз пилюлей рядом с ним значило бы удвоить одну и ту же
 * фразу на одной строке экрана без нового смысла (находка ревью 31.08.2026 —
 * до правки пилюля брала `label={row.title}` дословно). Пилюля здесь —
 * отдельный, короткий сигнал «эта строка диагностическая», а не второе имя
 * строки; полное объяснение — в подсказке {@link UNMATCHED_HINT}.
 */
export const UNMATCHED_PILL_LABEL = "без привязки";

/** Подсказка диагностической строки без каталожной привязки (§2.7). */
export const UNMATCHED_HINT =
  "У строк нет каталожной привязки — недоработан матчинг, строка диагностическая";

/** Заголовок свёрнутой строки «появились/исчезли» (§2.3, §2.9). */
export const collapsedTitle = (n: number) => `ещё ${n} работ появились или исчезли`;

/** Заголовок свёрнутой строки «прочие» (§2.3, §2.9). */
export const restTitle = (n: number) => `прочие ${n} строк статьи`;

/**
 * Число строк сметы группы на этапе (§2.4; макет 2026-08-29, строки 445-461:
 * «2 стр. · 248 м²», «2 стр. · 1 компл»). Печатается сокращением «N стр.»,
 * которое макет держит НЕИЗМЕНЯЕМЫМ что на 1, что на 2 — общий помощник
 * склонения `pluralRu` (`lib/format.ts`) сюда не подходит: он даёт суффикс
 * для слов с постоянной основой («объект»/«объекта»/«объектов»), а «строка»
 * меняет саму основу («строка»/«строки»/«строк»); с сокращением этот вопрос
 * вообще не встаёт — макет не склоняет его ни разу.
 */
export const estimateRowsLabel = (n: number) => `${n} стр.`;

