import { describe, expect, it } from "vitest";

import { roundDecimalPercent } from "./format";

/**
 * Текст округления с проверкой, что значение вообще разобралось.
 *
 * Нужен потому, что `roundDecimalPercent` возвращает `null` для отсутствующего
 * значения, и `tsc` справедливо не даёт читать `.text` без проверки. Вариант с `!`
 * отклонён: он глушит именно ту ошибку, из-за которой тест и стоит писать.
 */
function text(value: string | number | null | undefined): string {
  const rounded = roundDecimalPercent(value);
  expect(rounded, `значение ${value} не разобралось`).not.toBeNull();
  return rounded!.text;
}

/**
 * Округление отклонения (§4: точный Decimal, округление только на слое
 * представления).
 *
 * Смысл проверок — не «функция считает», а что она считает **без float**. Поэтому
 * значения взяты такие, на которых `Number()` расходится с целочисленным путём: без
 * них тест прошёл бы и на реализации через double, то есть не отличал бы правильное
 * от почти правильного.
 */
describe("roundDecimalPercent", () => {
  it("отсутствие значения — это не ноль", () => {
    // §10: «нет норматива» обязано быть отличимо от «0 %». Здесь различие в том,
    // что null не превращается ни в какой текст вообще.
    expect(roundDecimalPercent(null)).toBeNull();
    expect(roundDecimalPercent(undefined)).toBeNull();
    expect(roundDecimalPercent("")).toBeNull();
  });

  it("ноль показывается цифрой и без знака", () => {
    expect(roundDecimalPercent("0.000000000000000000")).toEqual({ text: "0,0%", sign: 0 });
  });

  it("знак ставится у обоих направлений", () => {
    expect(roundDecimalPercent("20.005000000000000000")).toEqual({ text: "+20,0%", sign: 1 });
    expect(roundDecimalPercent("-5.000000000000000000")).toEqual({ text: "-5,0%", sign: -1 });
  });

  it("округляет длинную дробь numeric до 0.1 п.п.", () => {
    // Ровно тот вид, в котором значение приходит из VIEW: numeric-деление даёт
    // больше пятнадцати знаков.
    expect(text("16.666666666666666667")).toBe("+16,7%");
    expect(text("-33.333333333333333333")).toBe("-33,3%");
  });

  it("половину округляет от нуля, а не по чётности разряда", () => {
    expect(text("0.05")).toBe("+0,1%");
    expect(text("0.15")).toBe("+0,2%");
    expect(text("-0.05")).toBe("-0,1%");
  });

  it("значение на границе округления не зависит от двоичного представления", () => {
    /*
      Вот на чём реализация через double разошлась бы с этой. Значения найдены
      замером (перебор x.xx5 и сверка `toFixed(1)` с точным округлением), а не
      подобраны на глаз: первая редакция теста утверждала расхождение на «8.045»,
      где его нет вовсе — 8.045 к одному знаку и есть 8,0, потому что до 8,0
      расстояние 0,045, а до 8,1 — 0,055.

      На перечисленных строках двоичное представление лежит чуть НИЖЕ половины, и
      `toFixed(1)` округляет вниз, тогда как точное значение — ровно половина и
      округляется вверх.
    */
    const divergent: [string, string, string][] = [
      ["0.35", "+0,4%", "0.3"],
      ["0.85", "+0,9%", "0.8"],
      ["0.95", "+1,0%", "0.9"],
      ["1.45", "+1,5%", "1.4"],
      ["1.95", "+2,0%", "1.9"],
    ];
    for (const [input, expected, floatResult] of divergent) {
      expect(roundDecimalPercent(input)!.text).toBe(expected);
      // Замер, а не утверждение: если поведение double однажды изменится, тест
      // скажет об этом, а не тихо потеряет смысл.
      expect(Number(input).toFixed(1)).toBe(floatResult);
    }
  });

  it("переносит разряд при округлении вверх", () => {
    expect(text("9.96")).toBe("+10,0%");
    expect(text("99.99")).toBe("+100,0%");
  });

  it("не показывает «минус ноль»", () => {
    // -0,0 % — артефакт: отклонения нет, а знак пугает.
    expect(roundDecimalPercent("-0.01")).toEqual({ text: "0,0%", sign: 0 });
  });

  it("огромное отклонение не теряет разрядов", () => {
    // BigInt снимает ограничение на разрядность: ставка против копеечного
    // норматива даёт проценты с большим числом знаков.
    expect(text("123456789012345.67")).toBe("+123456789012345,7%");
  });

  it("неразбираемое значение отдаётся как есть, а не прячется", () => {
    // Молча превратить пришедшее с сервера в «—» значило бы спрятать данные.
    expect(roundDecimalPercent("NaN")).toEqual({ text: "NaN", sign: 0 });
  });

  it("принимает число, хотя сервер присылает строку", () => {
    expect(text(20.005)).toBe("+20,0%");
  });
});
