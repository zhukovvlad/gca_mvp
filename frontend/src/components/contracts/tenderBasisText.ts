/**
 * Подсказка у запертых «Объект» и «Подрядчик» в правке связанного договора:
 * «берутся из тендера» плюс выход, зависящий от происхождения сметы.
 */
export function lockedPartiesHint(origin: EstimateOrigin | null): string {
  const base = "Объект и подрядчик берутся из тендера.";
  return origin === "from_offer"
    ? `${base} Если победитель не тот — удалите договор.`
    : `${base} Чтобы изменить, отвяжите договор.`;
}
