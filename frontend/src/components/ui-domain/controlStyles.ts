export const SEGMENTED_GROUP_CLASS = "inline-flex overflow-hidden rounded-lg border border-border";

/**
 * Сегмент в любом состоянии.
 *
 * Разделитель — левой рамкой сегмента, а не правой предыдущего: у макета
 * `button + button`, и у первого сегмента рамки нет вовсе (`first:border-l-0`),
 * иначе она удвоила бы рамку обоймы.
 *
 * Выключенный сегмент — подложка `sunken` и текст `fg-muted` вместо
 * полупрозрачности: `disabled:opacity-50` у `Button` гасит и подложку, и текст
 * разом, отчего сегмент выцветает в пятно вместо того, чтобы читаться как
 * «есть, но недоступно». `disabled:opacity-100` снимает базовое правило, и
 * порядок в `cn` тут не помог бы — это разные утилиты, а не одна.
 *
 * Заливка `surface` названа ЯВНО, хотя на карточке она и так белая: та же обойма
 * стоит внутри акцентной группы поправки на инфляцию, и прозрачный `ghost`
 * пропустил бы зелёную подложку внутрь переключателя.
 */
export const SEGMENTED_ITEM_CLASS =
  "rounded-none border-l border-l-border-subtle bg-surface text-fg-secondary first:border-l-0 " +
  "disabled:bg-surface-sunken disabled:text-fg-muted disabled:opacity-100";

/**
 * Нажатый сегмент — ТЁМНАЯ заливка `--action`, а не светло-зелёная `accent-soft`.
 *
 * `accent-soft` на этом экране занят другим смыслом: им же покрашены чипы класса
 * объекта и ячейки отклонения вниз, и выбранный сегмент сливался с ними в один
 * «зелёный» уровень. Ховер прибит к той же заливке: `ghost` у `Button` иначе
 * перекрашивает нажатый сегмент в `muted` под курсором.
 */
export const SEGMENTED_ITEM_ACTIVE_CLASS =
  "bg-action font-semibold text-action-text hover:bg-action-hover hover:text-action-text";
