/**
 * Оформление панели управления экрана сравнения — ОДНО место на все её группы:
 * «Показатель», «НДС», «Единая ставка», чипы класса объекта и «Режим» с рядом и
 * месяцем в поправке на инфляцию.
 *
 * Рецептом классов, а не компонентом: три группы отличаются не разметкой, а
 * данными и правилами недоступности — «Привести» гаснет, пока не выбран ряд, а
 * корзины приходят словарём. Компонент пришлось бы параметризовать до состояния,
 * в котором он читается хуже трёх явных `map`-ов; расходились же не структуры, а
 * четыре правила оформления, и теперь они лежат тут (`DEVIATION_TONE_CLASS` в
 * `ComparePage` — та же идиома).
 *
 * Источник — макет `2026-08-19-comparison-cost-chart-mockup.html`, правила
 * `.controls`, `.ctl`, `.ctl-lbl` и `.seg-ctl`. Имена переменных макета и токены
 * приложения НЕ совпадают (`AGENTS.md` §11), но цвета совпадают hex-в-hex:
 * `--action` = `--action-primary`, `--bd` = `--border-default`,
 * `--bd-subtle` = `--border-subtle`, `--sunken` = `--bg-surface-sunken`,
 * `--fg4` = `--text-muted`, `--fg3` = `--text-tertiary`.
 */

